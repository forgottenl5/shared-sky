#!/usr/bin/env python3
"""WX2 analysis (registration planned/WX2_PREREG.md). Reads out/wx2/*.jsonl and the 2025 Open-Meteo weather files; models flights stopped in
hard-stop hours and caught up afterwards at up to M_MAX times the normal rate; prints verdicts; writes planned/wx2_results_table.md."""
import glob, json, math
R = [json.loads(l) for f in sorted(glob.glob('out/wx2/*.jsonl')) for l in open(f) if l.strip()]
METROS = ('houston', 'dfw'); ARMS = ('S1', 'A2'); MS = (1, 1.5, 2)
WX = {'houston': 'data/openmeteo_houston_2025_weather.json', 'dfw': 'data/openmeteo_dfw_2025_weather.json'}
day = lambda t: int(t[11:13]) >= 13 or int(t[11:13]) <= 3          # WX1 daytime (UTC 13-03, about 7-8 am to 9-10 pm local)
def stops(m):
    x = json.load(open(WX[m]))['hourly']; D = [i for i, t in enumerate(x['time']) if day(t)]
    hard = [x['wind_gusts_10m'][i] >= 55 or x['precipitation'][i] >= 2.5 or x['weather_code'][i] in (95, 96, 99) for i in D]   # WX1 hard-stop label
    return D, hard
def schedule(m, mmax):
    """flown traffic per daytime hour (1 = normal): 0 in stop hours; afterwards min(mmax, 1 + backlog); backlog carries overnight"""
    D, hard = stops(m); b = 0.0; out = []
    for h in hard:
        if h: out.append(0.0); b += 1.0
        else: f = min(mmax, 1.0 + b); b -= f - 1.0; out.append(f)
    return out, b
def mean(a): return sum(a) / len(a)
def conflicts(m, a, M, key='v10'): x = [r for r in R if r['metro'] == m and r['arm'] == a and r['M'] == M]; return sum(r[key] for r in x) / len(x)
def exponent(m, a):   # least-squares slope of log conflicts on log M (M = 1, 1.5, 2)
    xs = [math.log(M) for M in MS]; ys = [math.log(conflicts(m, a, M)) for M in MS]; mx, my = mean(xs), mean(ys)
    return sum((x - mx) * (y - my) for x, y in zip(xs, ys)) / sum((x - mx) ** 2 for x in xs)
def c_of(m, a, f):    # conflicts per window at traffic f (0 for f = 0), interpolated by the fitted power law through M = 1
    return 0.0 if f <= 0 else conflicts(m, a, 1) * f ** exponent(m, a)
def annual_change(m, a, mmax): s, _ = schedule(m, mmax); return sum(c_of(m, a, f) for f in s) / (len(s) * conflicts(m, a, 1)) - 1
def dshare(m, a, M): x = [r for r in R if r['metro'] == m and r['arm'] == a and r['M'] == M]; n = sum(r['checked'] for r in x); return sum(r['delayed'] for r in x) / n
def cut(m, M): return 1 - conflicts(m, 'A2', M) / conflicts(m, 'S1', M)
P = []
def chk(name, ok, text): P.append((name, ok, text)); print('PASS' if ok else 'FAIL', name, text)
mc = [(m, a) for m in METROS for a in ARMS]
x1 = {k: exponent(*k) for k in mc}
chk('X1', all(1.7 <= v <= 2.3 for v in x1.values()), 'conflicts grow with traffic at exponent: ' + '; '.join(f'{m} {a} {v:.2f}' for (m, a), v in x1.items()))
x2 = {k: annual_change(*k, 1.5) for k in mc}
chk('X2', all(0.02 <= v <= 0.10 for v in x2.values()), 'yearly planned conflicts, stops + catch-up at 1.5x vs no weather: ' + '; '.join(f'{m} {a} {100 * v:+.1f} %' for (m, a), v in x2.items()))
x3 = {m: sum(1 for f in schedule(m, 1.5)[0] if f > 1) / len(schedule(m, 1.5)[0]) for m in METROS}
chk('X3', all(0.05 <= v <= 0.12 for v in x3.values()), 'share of daytime hours flown above normal traffic (catch-up at 1.5x): ' + ', '.join(f'{m} {100 * v:.1f} %' for m, v in x3.items()))
x4 = {k: dshare(*k, 2) / dshare(*k, 1) for k in mc}
chk('X4', all(v >= 1.5 for v in x4.values()), 'V2 delayed share at 2x traffic / at 1x: ' + '; '.join(f'{m} {a} {v:.2f}' for (m, a), v in x4.items()))
x5 = {m: (cut(m, 2), cut(m, 1)) for m in METROS}
chk('X5', all(abs(x5[m][0] - x5[m][1]) <= 0.05 for m in METROS), 'height-sharing cut at 2x vs 1x traffic: ' + '; '.join(f'{m} {100 * x5[m][0]:.0f} vs {100 * x5[m][1]:.0f} %' for m in METROS))
npass = sum(1 for _, ok, _ in P if ok)
T = ['# WX2 results table (generated by planned/wx2_analyze.py)', '', f'{npass} of {len(P)} predictions passed. Runs: {len(R)}.', '']
T += [f'- {"PASS" if ok else "FAIL"} {n}: {t}' for n, ok, t in P]
T += ['', '## Weather schedule, 2025 daytime hours', '', '| Metro | Daytime hours | Hard-stop hours | Hours above normal (1.5x / 2x catch-up) | Longest stop run (h) |', '|---|---|---|---|---|']
for m in METROS:
    D, hard = stops(m); run = best = 0
    for h in hard: run = run + 1 if h else 0; best = max(best, run)
    T.append(f'| {m} | {len(D)} | {sum(hard)} ({100 * sum(hard) / len(D):.1f} %) | {100 * x3[m]:.1f} % / {100 * sum(1 for f in schedule(m, 2)[0] if f > 1) / len(D):.1f} % | {best} |')
T += ['', '## Conflicts and plan-check cost by traffic multiplier (mean per 2-hour window, seeds 1-6)', '', '| Metro | Arm | M | v10 conflicts | close calls | V2 delayed | V2 cancelled |', '|---|---|---|---|---|---|---|']
for m in METROS:
    for a in ARMS:
        for M in MS:
            x = [r for r in R if r['metro'] == m and r['arm'] == a and r['M'] == M]; n = sum(r['checked'] for r in x)
            T.append(f'| {m} | {a} | {M} | {conflicts(m, a, M):.1f} | {conflicts(m, a, M, "close"):.1f} | {100 * sum(r["delayed"] for r in x) / n:.1f} % | {100 * sum(r["cancelled"] for r in x) / n:.2f} % |')
T += ['', '## Yearly planned conflicts vs no weather', '', '| Metro | Arm | catch-up up to 1.5x | up to 2x |', '|---|---|---|---|']
for m, a in mc: T.append(f'| {m} | {a} | {100 * annual_change(m, a, 1.5):+.1f} % | {100 * annual_change(m, a, 2):+.1f} % |')
open('planned/wx2_results_table.md', 'w').write('\n'.join(T) + '\n'); print(f'{npass} of {len(P)} passed')

#!/usr/bin/env python3
"""RISK2 analysis (registration planned/RISK2_PREREG.md). Reads out/risk2/*.jsonl (plan check V2 / V3) and out/risk1/*.jsonl (no check),
computes expected collisions with the RISK1 formula and base sizes, prints the verdict on each prediction, writes planned/risk2_results_table.md."""
import glob, json, math
R1 = [json.loads(l) for f in sorted(glob.glob('out/risk1/*.jsonl')) for l in open(f) if l.strip()]
R2 = [json.loads(l) for f in sorted(glob.glob('out/risk2/*.jsonl')) for l in open(f) if l.strip()]
for r in R1: r['check'] = 'NONE'
R = R1 + R2; METROS = ('houston', 'dfw'); ARMS = ('S1', 'A2'); K_RAD = math.sqrt(-2 * math.log(0.05)); K_VER = 1.96
LV = {'L0': (0, 0), 'L1': (3, 4), 'L2': (8, 13), 'L4': (30.48, 45.72)}
CASES = [('L0', 'L0', 0), ('L1', 'L1', 0), ('L2', 'L2', 0), ('L2 shared 0.95', 'L2', 0.95), ('L4 (lower bound)', 'L4', 0)]
WING = (0.65, 0.25); BIG = (1.5, 0.3)
Phi = lambda x: 0.5 * (1 + math.erf(x / math.sqrt(2)))
def band(d, W, s): return Phi((W - d) / s) - Phi((-W - d) / s) if s > 0 else (1.0 if abs(d) < W else 0.0)
def size(op): return WING if op == 'wing' else BIG
def expected(row, lv, rho):
    h95, v95 = LV[lv]; f = math.sqrt(1 - rho); sh = math.sqrt(2) * f * h95 / K_RAD; sz = math.sqrt(2) * f * v95 / K_VER; p = 0.0
    for opA, opB, dperp, dz, dh, vrel in row['enc']: A, B = size(opA), size(opB); p += band(dperp, A[0] + B[0], sh) * band(dz, A[1] + B[1], sz)
    return p
def rows(m, a, c): return [r for r in R if r['metro'] == m and r['arm'] == a and r['check'] == c]
def rate(m, a, c, lv, rho): x = rows(m, a, c); return 1e5 * sum(expected(r, lv, rho) for r in x) / sum(r['flightHours'] for r in x)
def removal(m, a, c, lv, rho): r0 = rate(m, a, 'NONE', lv, rho); return 1 - rate(m, a, c, lv, rho) / r0 if r0 else float('nan')
def dshare(m, a, c): x = rows(m, a, c); n = sum(r['checked'] for r in x); return sum(r['delayed'] for r in x) / n if n else float('nan')
def cshare(m, a, c): x = rows(m, a, c); n = sum(r['checked'] for r in x); return sum(r['cancelled'] for r in x) / n if n else float('nan')
P = []
def chk(name, ok, text): P.append((name, ok, text)); print('PASS' if ok else 'FAIL', name, text)
mc = [(m, a) for m in METROS for a in ARMS]
q1 = {k: removal(*k, 'V2', 'L0', 0) for k in mc}
chk('Q1', all(v != v or v >= 0.95 for v in q1.values()) and any(v == v for v in q1.values()), 'V2 removal of L0 risk (nan = no L0 risk without the check): ' + '; '.join(f'{m} {a} {100 * v:.0f} %' for (m, a), v in q1.items()))
q2 = {k: removal(*k, 'V2', 'L2', 0) for k in mc}
chk('Q2', all(0.20 <= v <= 0.60 for v in q2.values()), 'V2 removal of L2 risk: ' + '; '.join(f'{m} {a} {100 * v:.0f} %' for (m, a), v in q2.items()))
q3 = {k: removal(*k, 'V3', 'L2', 0) for k in mc}
chk('Q3', all(v >= 0.90 for v in q3.values()), 'V3 removal of L2 risk: ' + '; '.join(f'{m} {a} {100 * v:.0f} %' for (m, a), v in q3.items()))
q4 = {m: (rate(m, 'A2', 'V2', 'L2', 0), rate(m, 'S1', 'V2', 'L2', 0)) for m in METROS}
chk('Q4', all(q4[m][0] < q4[m][1] for m in METROS), 'L2 risk with V2, shared-out vs best-sourced heights: ' + '; '.join(f'{m} {q4[m][0]:.3g} vs {q4[m][1]:.3g}' for m in METROS))
q5 = {k: dshare(*k, 'V3') / dshare(*k, 'V2') for k in mc}
chk('Q5', all(v >= 1.5 for v in q5.values()), 'delayed share V3 / V2: ' + '; '.join(f'{m} {a} {v:.2f}' for (m, a), v in q5.items()))
npass = sum(1 for _, ok, _ in P if ok)
T = ['# RISK2 results table (generated by planned/risk2_analyze.py)', '', f'{npass} of {len(P)} predictions passed. Rows: RISK2 {len(R2)}, RISK1 (no check) {len(R1)}.', '']
T += [f'- {"PASS" if ok else "FAIL"} {n}: {t}' for n, ok, t in P]
T += ['', '## Expected collisions per 100,000 flight hours (base sizes), by plan check', '', '| Metro | Arm | Case | No check | V2 | V3 | Removed by V2 | Removed by V3 |', '|---|---|---|---|---|---|---|---|']
for m in METROS:
    for a in ARMS:
        for name, lv, rho in CASES:
            r0, r2, r3 = (rate(m, a, c, lv, rho) for c in ('NONE', 'V2', 'V3')); f = lambda v: f'{100 * (1 - v / r0):.0f} %' if r0 else 'n/a'
            T.append(f'| {m} | {a} | {name} | {r0:.3g} | {r2:.3g} | {r3:.3g} | {f(r2)} | {f(r3)} |')
T += ['', '## Cost of the check (flights checked in the measured window, still air)', '', '| Metro | Arm | Check | Delayed | Cancelled | Mean delay of delayed flights (min) |', '|---|---|---|---|---|---|']
for m in METROS:
    for a in ARMS:
        for c in ('V2', 'V3'):
            x = rows(m, a, c); d = sum(r['delayed'] for r in x); md = sum(r['meanD'] * r['delayed'] for r in x) / d / 60 if d else 0
            T.append(f'| {m} | {a} | {c} | {100 * dshare(m, a, c):.1f} % | {100 * cshare(m, a, c):.2f} % | {md:.1f} |')
T += ['', '## Height-sharing cut in collision risk, by check', '', '| Metro | Case | No check | V2 | V3 |', '|---|---|---|---|---|']
for m in METROS:
    for name, lv, rho in CASES:
        cells = []
        for c in ('NONE', 'V2', 'V3'):
            s1 = rate(m, 'S1', c, lv, rho); cells.append(f'{100 * (1 - rate(m, "A2", c, lv, rho) / s1):.0f} %' if s1 else 'n/a')
        T.append(f'| {m} | {name} | ' + ' | '.join(cells) + ' |')
open('planned/risk2_results_table.md', 'w').write('\n'.join(T) + '\n'); print(f'{npass} of {len(P)} passed')

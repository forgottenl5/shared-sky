#!/usr/bin/env python3
"""RECHECK_B analysis (planned/RECHECK_B_PREREG.md). Written and committed before the re-check runs.

Runs the ERRORS1 and ERRORS2 analysis scripts, unchanged, in the repo root (original runs) and in the re-check shadow root
(independent error streams), pairs their verdict lines in order, and scores B1-B3.
Usage: python3 planned/recheck_compare_b.py <shadow root>   (from the repo root) -> markdown on stdout
"""
import glob, json, os, re, subprocess, sys
REPO = os.getcwd(); NEW = os.path.abspath(sys.argv[1])
V = re.compile(r"^(?:- )?(PASS|FAIL) ([A-Z]\d+[a-z]?)\b(.*)")
def verdicts(root, script):
    out = subprocess.run([sys.executable, f"planned/{script}"], cwd=root, capture_output=True, text=True).stdout
    return [m.groups() for m in map(V.match, out.splitlines()) if m]
def rows(root, s): return [json.loads(l) for f in sorted(glob.glob(os.path.join(root, f"out/{s}/*.jsonl"))) for l in open(f) if l.strip()]
KEY = ("study", "metro", "arm", "level", "rho", "shared", "seed")
strip = lambda r: {k: v for k, v in r.items() if k != "wall_s"}

P = print
P("# RECHECK_B results table (generated by planned/recheck_compare_b.py)\n")
flips, total, nums = [], 0, []
for S, script in (("ERRORS1", "errors1_analyze.py"), ("ERRORS2", "errors2_analyze.py")):
    old, new = verdicts(REPO, script), verdicts(NEW, script)
    P(f"## {S}\n"); P("| id | original | re-check |"); P("|---|---|---|")
    if [o[1] for o in old] != [n[1] for n in new]: P(f"| — | PREDICTION IDS DIFFER: {[o[1] for o in old]} vs {[n[1] for n in new]} | |")
    for (vo, io, to), (vn, i, tn) in zip(old, new):
        total += 1; ch = vo != vn
        if ch: flips.append((S, i))
        P(f"| {i} | {vo}: {to.strip()[:150]} | {vn}: {tn.strip()[:150]}{' **CHANGED**' if ch else ''} |")
        for a, b in zip(re.findall(r"(-?\d+) %", to), re.findall(r"(-?\d+) %", tn)): nums.append((S, i, int(a), int(b)))
    P("")
# rows without any error (level L0, no shared field) cannot depend on the error streams: must be identical (check, reported)
same = bad = 0
for s in ("errors1", "errors2"):
    o = {tuple(r.get(k) for k in KEY): strip(r) for r in rows(REPO, s)}
    for r in rows(NEW, s):
        k = tuple(r.get(k) for k in KEY)
        if r.get("level") == "L0" and not r.get("rho"): same += o.get(k) == strip(r); bad += o.get(k) != strip(r)
P(f"Check: rows with no errors (L0) identical to the original: {same} identical, {bad} different.\n")
P("## Registered predictions\n")
big = [x for x in nums if abs(x[3] - x[2]) > 10]
cuts = [x for x in nums if x[1] in ("E1", "E2", "E3", "E4", "E5", "E6a", "D1", "D2", "D3", "D4", "D5")]
mx = max((abs(b - a) for *_, a, b in cuts), default=0)
P(f"- **B1** (every reported cut in ERRORS1 E1-E5, E6a and ERRORS2 D1-D5 moves by at most 10 points): largest move {mx} points. {'**PASS**' if mx <= 10 else '**FAIL**'}")
c = [x for x in nums if x[1] in ("C1", "C2", "C3", "C4", "C5")]; mc = max((abs(b - a) for *_, a, b in c), default=0)
P(f"- **B2** (every percentage in ERRORS2 C1-C5 moves by at most 10 points): largest move {mc} points. {'**PASS**' if mc <= 10 else '**FAIL**'}")
P(f"- **B3** (at most 3 of the {total} original verdicts change): {len(flips)} changed. {'**PASS**' if len(flips) <= 3 else '**FAIL**'}")
for S, i in flips: P(f"  - {S} {i}")
P(f"\nAll percentage pairs moving more than 10 points: {big if big else 'none'}")

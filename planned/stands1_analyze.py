"""STANDS1 analysis: P S1-S6 from out/stands1_*.json; writes planned/stands1_results_table.md. Usage: python3 -I planned/stands1_analyze.py"""
import json, glob, math, statistics as st
R, k3m, k2b = [], 0, 0
for f in sorted(glob.glob('out/stands1_*.json')):
    d = json.load(open(f)); R += d['rows']; k3m += d['k3missing']; k2b += d['k2bad']
NS = {'DFW': 4, 'HOU': 3}; RATES = [1.5, 3, 6, 12]; UNI = [2, 3, 4, 5, 6, 8, 10, 12, 14, 16, 20, 24]
def get(m, r, s, a): return next(x for x in R if x['metro'] == m and x['r'] == r and x['s'] == s and x['arm'] == a)
def med(v): return st.median(v)
res = []
def add(n, ok, d): res.append((n, ok, d)); print(('PASS ' if ok else 'FAIL ') + n, d)
print(f'K2 bad {k2b}, K3 missing {k3m}, rows {len(R)}')
# S1
det = {}; ok1 = True
for m in NS:
    for r in RATES:
        a = [get(m, r, s, 'NET3') for s in range(1, 11)]; b = [get(m, r, s, 'UNL') for s in range(1, 11)]
        ds = abs(med([x['servedShare'] for x in a]) - med([x['servedShare'] for x in b])) * 100; dw = abs(med([x['medWait'] for x in a]) - med([x['medWait'] for x in b]))
        det[f'{m} {r}'] = (round(ds, 2), round(dw, 1)); ok1 &= ds <= 2 and dw <= 60
add('S1 UNL v4 matches NET3 v3 (2 points, 60 s)', ok1, det)
realm = {f'{m} {r}': sum(get(m, r, s, 'REAL')['meets'] for s in range(1, 11)) for m in NS for r in RATES}
add('S2 REAL meets >= 6/10 at r 1.5 and 3, both metros', all(realm[f'{m} {r}'] >= 6 for m in NS for r in (1.5, 3)), realm)
add('S3 REAL meets <= 4/10 at r 12 (both) and r 6 (DFW)', realm['DFW 12'] <= 4 and realm['HOU 12'] <= 4 and realm['DFW 6'] <= 4, realm)
sstar, base = {}, {}
for m in NS:
    for r in RATES:
        v = []
        for s in range(1, 11):
            got = next((u for u in UNI if get(m, r, s, 'S' + str(u))['meets']), 99); v.append(got)
        Fm = med([get(m, r, s, 'UNL')['F'] for s in range(1, 11)]); sstar[f'{m} {r}'] = med(v); base[f'{m} {r}'] = math.ceil(Fm / NS[m])
add('S4 S* >= ceil(F/n)+2 in all cells', all(sstar[k] >= base[k] + 2 for k in sstar), {k: (sstar[k], base[k]) for k in sstar})
add('S5 S* <= ceil(F/n)+6 in all cells', all(sstar[k] <= base[k] + 6 for k in sstar), {k: (sstar[k], base[k]) for k in sstar})
hub = {'DFW': 'DFWc', 'HOU': 'IAH'}; d6 = {}; ok6 = True
for m in NS:
    for r in (6, 12):
        b = base[f'{m} {r}']; arm = 'S' + str(min([u for u in UNI if u >= b]))
        wins = 0; n = 0
        for s in range(1, 11):
            x = get(m, r, s, arm)
            if x.get('cannotPark'): continue
            n += 1; sp = x['siteHoldP95']; top = max(sp, key=sp.get)
            wins += (top == hub[m] and sp[top] > 0)
        d6[f'{m} {r} {arm}'] = f'{wins}/{n}'; ok6 &= n > 0 and wins > n / 2
add('S6 hub has the largest hold at S = ceil(F/n)', ok6, d6)
n = sum(1 for x in res if x[1]); print(f'\n{n} of 6 predictions passed')
L = ['# STANDS1 results table (generated by planned/stands1_analyze.py)\n', f'K2 bad {k2b}; K3 missing {k3m}; rows {len(R)}\n']
for m in NS:
    L += [f'\n## {m}\n', '| r | fleet (median) | ceil(F/n) | S* median | REAL meets | REAL served % | REAL hold p95 s | REAL below % | UNL served % | UNL hold p95 s |', '|---|---|---|---|---|---|---|---|---|---|']
    for r in RATES:
        RE = [get(m, r, s, 'REAL') for s in range(1, 11)]; U = [get(m, r, s, 'UNL') for s in range(1, 11)]; ok = [x for x in RE if not x.get('cannotPark')]
        f = lambda xs, k, sc=1: (round(med([x[k] for x in xs]) * sc, 1) if xs else 'cannot park')
        L.append(f"| {r} | {med([x['F'] for x in U])} | {base[f'{m} {r}']} | {sstar[f'{m} {r}']} | {realm[f'{m} {r}']}/10 | {f(ok,'servedShare',100)} | {f(ok,'holdP95')} | {f(ok,'belowShare',100)} | {f(U,'servedShare',100)} | {f(U,'holdP95')} |")
    L.append('\nUniform stands per site, seeds meeting the criterion (of 10):\n')
    L.append('| r | ' + ' | '.join('S' + str(u) for u in UNI) + ' |'); L.append('|---' * (len(UNI) + 1) + '|')
    for r in RATES: L.append(f'| {r} | ' + ' | '.join(str(sum(get(m, r, s, "S" + str(u))["meets"] for s in range(1, 11))) for u in UNI) + ' |')
L.append('\n## Predictions\n'); L += [f"- {'PASS' if ok else 'FAIL'} {a}: {b}" for a, ok, b in res]
open('planned/stands1_results_table.md', 'w').write('\n'.join(L) + '\n')

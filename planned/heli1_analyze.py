#!/usr/bin/env python3
"""HELI1 analysis (registration planned/HELI1_PREREG.md). Reads out/heli1/tracks/*.jsonl and out/heli1/density_*.json; prints verdicts; writes planned/heli1_results_table.md."""
import glob, json, math, collections
ELEV = {'houston': 15.0, 'dfw': 180.0}; SENS = {'houston': (-30, 30), 'dfw': (-50, 50)}
DAY = lambda ts: (ts // 3600) % 24 >= 13 or (ts // 3600) % 24 <= 3
T = [json.loads(l) for f in sorted(glob.glob('out/heli1/tracks/*.jsonl')) for l in open(f) if l.strip()]
D = {}
for m in ELEV:
    for a in ('S1', 'A2'): d = json.load(open(f'out/heli1/density_{m}_{a}.json')); D[m, a] = d
def xy(m, lat, lon): d = D[m, 'S1']; return (lon - d['lon0']) * 111320 * math.cos(math.radians(d['lat0'])), (lat - d['lat0']) * 110540
def seconds(m, elev_shift=0.0):
    """list of (x, y, agl_m, weight_s) for in-zone daytime points of metro m"""
    z = D[m, 'S1']['zone']; out = []
    for r in T:
        if r['metro'] != m: continue
        p = r['pts']
        for i, q in enumerate(p):
            if q[3] == 'ground' or not isinstance(q[3], (int, float)) or not DAY(q[0]): continue
            w = min(60, p[i + 1][0] - q[0]) if i + 1 < len(p) else 0
            if w <= 0: continue
            x, y = xy(m, q[1], q[2])
            if abs(x) > z or abs(y) > z: continue
            out.append((x, y, q[3] * 0.3048 - ELEV[m] - elev_shift, w))
    return out
def lam(m, a, x, y, h):
    d = D[m, a]; c = d['cells']; i, j, k = math.floor(x / d['cell']), math.floor(y / d['cell']), math.floor(h / d['layer'])
    return sum(c.get(f'{i + di},{j + dj},{k + dk}', 0) for di in (-1, 0, 1) for dj in (-1, 0, 1) for dk in (-1, 0, 1))
P = []
def chk(n, ok, t): P.append((n, ok, t)); print('PASS' if ok else 'FAIL', n, t)
S = {m: seconds(m) for m in ELEV}
tot = {m: sum(w for *_, w in S[m]) for m in ELEV}
low = {m: [s for s in S[m] if s[2] < 150] for m in ELEV}
band = {m: [s for s in S[m] if 46 <= s[2] <= 121] for m in ELEV}
sh = lambda L, m: sum(w for *_, w in L[m]) / tot[m]
chk('H1', all(sh(low, m) < 0.15 for m in ELEV), 'share of helicopter seconds in the zone below 150 m: ' + '; '.join(f'{m} {100 * sh(low, m):.1f} %' for m in ELEV))
chk('H2', all(sh(band, m) < 0.08 for m in ELEV), 'share inside the drone band 46-121 m: ' + '; '.join(f'{m} {100 * sh(band, m):.1f} %' for m in ELEV))
top = {}
for m in ELEV:
    c = collections.Counter()
    for x, y, h, w in low[m]: c[(math.floor(x / 1000), math.floor(y / 1000))] += w
    v = sorted(c.values(), reverse=True); n = max(1, math.ceil(0.05 * len(v))); top[m] = (sum(v[:n]) / sum(v) if v else 0, len(v))
chk('H3', all(top[m][0] > 0.5 for m in ELEV), 'share of low helicopter seconds in the busiest 5 % of 1 km cells: ' + '; '.join(f'{m} {100 * top[m][0]:.0f} % ({top[m][1]} cells)' for m in ELEV))
ml = {}
for m in ELEV:
    for a in ('S1', 'A2'):
        w = sum(s[3] for s in low[m]); ml[m, a] = sum(lam(m, a, x, y, h) * ww for x, y, h, ww in low[m]) / w if w else 0
chk('H4', all(v < 0.05 for v in ml.values()), 'mean drones in the 450 x 450 x 60 m box around low-flying helicopters: ' + '; '.join(f'{m} {a} {v:.4f}' for (m, a), v in ml.items()))
rel = {m: abs(ml[m, 'A2'] - ml[m, 'S1']) / ml[m, 'S1'] if ml[m, 'S1'] else 0 for m in ELEV}
chk('H5', all(v < 0.3 for v in rel.values()), 'A2 vs S1 mean exposure, relative difference: ' + '; '.join(f'{m} {100 * v:.0f} %' for m, v in rel.items()))
npass = sum(1 for _, ok, _ in P if ok)
R = ['# HELI1 results table (generated by planned/heli1_analyze.py)', '', f'{npass} of {len(P)} predictions passed. Aircraft-days: {len(T)}; days: {len(glob.glob("out/heli1/tracks/*.jsonl"))}.', '']
R += [f'- {"PASS" if ok else "FAIL"} {n}: {t}' for n, ok, t in P]
R += ['', '## Helicopter time in the zone (daytime hours, UTC 13-03)', '', '| Metro | Hours | Below 150 m | In drone band 46-121 m | Below 46 m | Aircraft-days |', '|---|---|---|---|---|---|']
for m in ELEV:
    b46 = [s for s in S[m] if s[2] < 46]; R.append(f'| {m} | {tot[m] / 3600:.1f} | {100 * sh(low, m):.1f} % | {100 * sh(band, m):.1f} % | {100 * sh(dict(m=b46), "m") if False else 100 * sum(w for *_, w in b46) / tot[m]:.1f} % | {sum(1 for r in T if r["metro"] == m)} |')
R += ['', '## Ground-elevation sensitivity (not scored): share below 150 m / in the drone band', '', '| Metro | Elevation shift (m) | Below 150 m | In band |', '|---|---|---|---|']
for m in ELEV:
    for sft in (SENS[m][0], 0, SENS[m][1]):
        s = seconds(m, sft); t = sum(w for *_, w in s); R.append(f'| {m} | {sft:+d} | {100 * sum(w for *_, h, w in s if h < 150) / t:.1f} % | {100 * sum(w for *_, h, w in s if 46 <= h <= 121) / t:.1f} % |')
R += ['', '## Exposure of low-flying helicopters to drones (mean drones in the 450 x 450 x 60 m box)', '', '| Metro | Arm | Mean | Share of low helicopter seconds with at least 0.01 |', '|---|---|---|---|']
for m in ELEV:
    for a in ('S1', 'A2'):
        w = sum(s[3] for s in low[m]); R.append(f'| {m} | {a} | {ml[m, a]:.4f} | {100 * sum(ww for x, y, h, ww in low[m] if lam(m, a, x, y, h) >= 0.01) / w:.1f} % |')
R += ['', '## Helicopter types (aircraft-days)', ''] + [f'- {m}: ' + ', '.join(f'{t} {n}' for t, n in collections.Counter(r['type'] for r in T if r['metro'] == m).most_common(8)) for m in ELEV]
open('planned/heli1_results_table.md', 'w').write('\n'.join(R) + '\n'); print(f'{npass} of {len(P)} passed')

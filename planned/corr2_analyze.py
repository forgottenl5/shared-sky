#!/usr/bin/env python3
"""CORR2 analysis (registration planned/CORR2_PREREG.md). Corridor runs out/corr2/*.jsonl against HEADLINE2 straight runs out/headline2/*.jsonl."""
import json, glob, statistics as st
C = [json.loads(l) for f in glob.glob('out/corr2/*.jsonl') for l in open(f) if l.strip()]
S = [json.loads(l) for f in glob.glob('out/headline2/*.jsonl') for l in open(f) if l.strip()]
def mean(rows, m, arm): v = [r['v10'] for r in rows if r['metro'] == m and r['arm'] == arm]; return sum(v) / len(v) / 2, len(v)   # per hour (2 h measured)
P = []
def chk(n, ok, t): P.append((n, ok, t)); print('PASS' if ok else 'FAIL', n, t)
res = {}
for m in ('houston', 'dfw'):
    s1c, n1 = mean(C, m, 'S1'); a2c, n2 = mean(C, m, 'A2'); s1s, _ = mean(S, m, 'S1'); a2s, _ = mean(S, m, 'A2')
    res[m] = dict(s1c=s1c, a2c=a2c, s1s=s1s, a2s=a2s, cutc=1 - a2c / s1c, cuts=1 - a2s / s1s, n=(n1, n2))
for m, r in res.items(): print(m, {k: round(v, 3) if isinstance(v, float) else v for k, v in r.items()})
chk('C1', all(0.55 <= r['cutc'] <= 0.85 for r in res.values()), ', '.join(f"{m} cut with corridors {100 * r['cutc']:.0f} %" for m, r in res.items()))
chk('C2', all(abs(r['cutc'] - r['cuts']) <= 0.10 for r in res.values()), ', '.join(f"{m} {100 * r['cutc']:.0f} vs straight {100 * r['cuts']:.0f} %" for m, r in res.items()))
chk('C3', all(0.8 <= r['s1c'] / r['s1s'] <= 1.5 for r in res.values()), ', '.join(f"{m} S1 {r['s1c']:.1f} vs {r['s1s']:.1f}/h ({r['s1c'] / r['s1s']:.2f}x)" for m, r in res.items()))
npass = sum(1 for _, ok, _ in P if ok)
L = ['# CORR2 results table (generated by planned/corr2_analyze.py)', '', f'{npass} of {len(P)} predictions passed.', ''] + [f'- {"PASS" if ok else "FAIL"} {n}: {t}' for n, ok, t in P]
L += ['', '| Metro | S1 straight /h | S1 corridors /h | A2 straight /h | A2 corridors /h | Cut straight | Cut corridors | runs (S1, A2) |', '|---|---|---|---|---|---|---|---|']
L += [f"| {m} | {r['s1s']:.1f} | {r['s1c']:.1f} | {r['a2s']:.1f} | {r['a2c']:.1f} | {100 * r['cuts']:.0f} % | {100 * r['cutc']:.0f} % | {r['n']} |" for m, r in res.items()]
pc = {}
for m in ('houston', 'dfw'):
    for arm in ('S1', 'A2'):
        tot = {}
        for r in C:
            if r['metro'] == m and r['arm'] == arm:
                for k, v in r['pairs'].items(): tot[k] = tot.get(k, 0) + v
        pc[(m, arm)] = tot
L += ['', 'Pairs with corridors (sum over seeds): ' + '; '.join(f"{m} {arm}: " + ', '.join(f'{k} {v}' for k, v in sorted(t.items(), key=lambda kv: -kv[1])) for (m, arm), t in pc.items())]
open('planned/corr2_results_table.md', 'w').write('\n'.join(L) + '\n'); print(f'{npass} of {len(P)} passed; wrote planned/corr2_results_table.md')

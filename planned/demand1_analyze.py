#!/usr/bin/env python3
"""DEMAND1 analysis (registration planned/DEMAND1_PREREG.md). Analysis-only: combines the WX2 traffic runs (out/wx2) with an assumed
two-peak daily delivery profile; prints verdicts; writes planned/demand1_results_table.md."""
import glob, json, math
R = [json.loads(l) for f in sorted(glob.glob('out/wx2/*.jsonl')) for l in open(f) if l.strip()]
METROS = ('houston', 'dfw'); ARMS = ('S1', 'A2'); MS = (1, 1.5, 2); HOURS = list(range(7, 22))   # 15 operating hours, 07:00-21:59 local
def shape(h): return math.exp(-0.5 * (h + 0.5 - 12) ** 2) + math.exp(-0.5 * (h + 0.5 - 18) ** 2)   # lunch and dinner peaks (sigma 1 h), hour centres
def profile(P):
    """hourly traffic multipliers, mean 1, busiest hour = P x mean: base + a * shape(h)"""
    s = [shape(h) for h in HOURS]; ms = sum(s) / len(s)   # with base b and amplitude a: mean = b + a ms = 1, max = b + a max(s) = P
    a = (P - 1) / (max(s) - ms); b = 1 - a * ms; return [b + a * v for v in s]
def mean(a): return sum(a) / len(a)
def conflicts(m, a, M): x = [r for r in R if r['metro'] == m and r['arm'] == a and r['M'] == M]; return sum(r['v10'] for r in x) / len(x)
def exponent(m, a):
    xs = [math.log(M) for M in MS]; ys = [math.log(conflicts(m, a, M)) for M in MS]; mx, my = mean(xs), mean(ys)
    return sum((x - mx) * (y - my) for x, y in zip(xs, ys)) / sum((x - mx) ** 2 for x in xs)
def daily(m, a, P): k = exponent(m, a); return sum(conflicts(m, a, 1) * f ** k for f in profile(P))
def flat(m, a): return len(HOURS) * conflicts(m, a, 1)
def cut(m, P): return 1 - daily(m, 'A2', P) / daily(m, 'S1', P)
P_ = []
def chk(name, ok, text): P_.append((name, ok, text)); print('PASS' if ok else 'FAIL', name, text)
mc = [(m, a) for m in METROS for a in ARMS]
y1 = {k: daily(*k, 2.0) / flat(*k) - 1 for k in mc}
chk('Y1', all(0.15 <= v <= 0.45 for v in y1.values()), 'daily planned conflicts, two-peak demand (busiest hour 2x average) vs flat: ' + '; '.join(f'{m} {a} {100 * v:+.0f} %' for (m, a), v in y1.items()))
y2 = {k: (2.0 ** exponent(*k)) for k in mc}
chk('Y2', all(3.0 <= v <= 5.0 for v in y2.values()), 'busiest-hour conflicts vs flat-demand hour: ' + '; '.join(f'{m} {a} {v:.2f}x' for (m, a), v in y2.items()))
y3 = {m: (cut(m, 2.0), 1 - conflicts(m, 'A2', 1) / conflicts(m, 'S1', 1)) for m in METROS}
chk('Y3', all(abs(y3[m][0] - y3[m][1]) <= 0.03 for m in METROS), 'height-sharing cut over a two-peak day vs flat: ' + '; '.join(f'{m} {100 * y3[m][0]:.1f} vs {100 * y3[m][1]:.1f} %' for m in METROS))
npass = sum(1 for _, ok, _ in P_ if ok)
T = ['# DEMAND1 results table (generated by planned/demand1_analyze.py)', '', f'{npass} of {len(P_)} predictions passed. Traffic runs: WX2, {len(R)}.', '']
T += [f'- {"PASS" if ok else "FAIL"} {n}: {t}' for n, ok, t in P_]
T += ['', '## Assumed daily profiles (traffic multiplier by local hour, mean 1)', '', '| Busiest hour / average | ' + ' | '.join(f'{h:02d}' for h in HOURS) + ' |', '|---|' + '---|' * len(HOURS)]
for P in (1.5, 2.0, 2.5): T.append(f'| {P} | ' + ' | '.join(f'{v:.2f}' for v in profile(P)) + ' |')
T += ['', '## Daily planned conflicts vs flat demand (power law fitted to WX2 M = 1, 1.5, 2; P = 2.5 extrapolates beyond M = 2)', '', '| Metro | Arm | Exponent | Busiest 1.5x | 2x | 2.5x |', '|---|---|---|---|---|---|']
for m, a in mc: T.append(f'| {m} | {a} | {exponent(m, a):.2f} | ' + ' | '.join(f'{100 * (daily(m, a, P) / flat(m, a) - 1):+.0f} %' for P in (1.5, 2.0, 2.5)) + ' |')
T += ['', '## Height-sharing cut over the day', '', '| Metro | Flat | 1.5x | 2x | 2.5x |', '|---|---|---|---|---|']
for m in METROS: T.append(f'| {m} | {100 * (1 - conflicts(m, "A2", 1) / conflicts(m, "S1", 1)):.1f} % | ' + ' | '.join(f'{100 * cut(m, P):.1f} %' for P in (1.5, 2.0, 2.5)) + ' |')
open('planned/demand1_results_table.md', 'w').write('\n'.join(T) + '\n'); print(f'{npass} of {len(P_)} passed')

#!/usr/bin/env python3
"""CAPACITY1 analysis (planned/CAPACITY1_PREREG.md). Writes planned/capacity1_results_table.md."""
import json, glob
rd = lambda p: [json.loads(l) for f in glob.glob(p) for l in open(f) if l.strip()]
R = rd('out/capacity1/*.jsonl'); C = [r for r in R if r['part'] == 'c']; U = [r for r in R if r['part'] == 'u']
M, OPS, K = ('houston', 'dfw'), ('wing', 'zipline', 'amazon'), [0.1, 0.25, 0.5, 0.75, 1, 1.5]
CFG = [('A0', 'N2'), ('A2', 'N2'), ('G1', 'N2'), ('G1', 'V135')]
def cc(m, h, v, ax='k', x=1): return [r for r in C if r['metro'] == m and r['heights'] == h and r['vol'] == v and r['axis'] == ax and r['x'] == x]
def held(rows, op='all'):
    n = sum(r['cost'][op]['n'] for r in rows if op in r['cost']); return sum(r['cost'][op]['delayed'] + r['cost'][op]['cancelled'] for r in rows if op in r['cost']) / n if n else float('nan')
def ok_at(m, h, v, x): rows = cc(m, h, v, 'k', x); return held(rows) <= 0.10 and all(not held(rows, op) > 0.25 for op in OPS)
def capacity(m, h, v):
    best = None
    for x in K:
        if ok_at(m, h, v, x): best = x
    return best if best is not None else 0
def first_fail(m, h, v, op):
    lim = 0.25 if op != 'all' else 0.10
    for x in K:
        if held(cc(m, h, v, 'k', x), op) > lim: return x
    return float('inf')
def bw(m, a, x): return sum(r['cross']['h30v10'] for r in U if r['metro'] == m and r['arm'] == a and r['x'] == x)
cut = lambda m, x: 1 - bw(m, 'A2', x) / bw(m, 'S1', x) if bw(m, 'S1', x) else float('nan')
P = []
def chk(n, ok, t): P.append((n, ok, t)); print('PASS' if ok else 'FAIL', n, t)
pc = lambda x: f'{100 * x:.1f} %'
chk('C1', all(held(cc(m, h, v, 'k', 0.1)) < held(cc(m, h, v, 'k', 0.5)) < held(cc(m, h, v, 'k', 1)) < held(cc(m, h, v, 'k', 1.5)) for m in M for h, v in CFG),
    '; '.join(f'{m} {h}/{v} ' + '/'.join(f'{100 * held(cc(m, h, v, "k", x)):.1f}' for x in (0.1, 0.5, 1, 1.5)) for m in M for h, v in CFG))
chk('C2', all(held(cc(m, 'A0', 'N2', 'k', 0.25)) >= 0.10 for m in M), '; '.join(f'{m} A0 N2 at k=0.25 {pc(held(cc(m, "A0", "N2", "k", 0.25)))}' for m in M))
chk('C3', all(held(cc(m, 'A2', 'N2', 'k', 0.5)) <= 0.10 for m in M), '; '.join(f'{m} A2 N2 at k=0.5 {pc(held(cc(m, "A2", "N2", "k", 0.5)))}' for m in M))
chk('C4', all(first_fail(m, h, 'N2', 'amazon') < first_fail(m, h, 'N2', 'all') for m in M for h in ('A0', 'A2')),
    '; '.join(f'{m} {h}: Amazon > 25 % from k={first_fail(m, h, "N2", "amazon")}, all > 10 % from k={first_fail(m, h, "N2", "all")}' for m in M for h in ('A0', 'A2')))
cap = {(m, h, v): capacity(m, h, v) for m in M for h, v in CFG}
chk('C5', all(all(cap[(m, 'G1', 'V135')] >= cap[(m, h, v)] for h, v in CFG) and cap[(m, 'G1', 'V135')] > cap[(m, 'A0', 'N2')] for m in M),
    '; '.join(f'{m} ' + ', '.join(f'{h}/{v} {cap[(m, h, v)]}' for h, v in CFG) for m in M))
d6 = [(m, h, f, held(cc(m, h, 'N2', 'f', f)) - held(cc(m, h, 'N2', 'k', f))) for m in M for h in ('A0', 'A2') for f in (0.25, 0.5)]
chk('C6', all(abs(d) <= 0.03 for *_, d in d6), '; '.join(f'{m} {h} f={f}: {100 * d:+.1f} pts' for m, h, f, d in d6))
chk('C7', all(abs(cut(m, x) - cut(m, 1)) <= 0.10 for m in M for x in (0.25, 0.5, 0.75, 1.5)), '; '.join(f'{m} ' + '/'.join(f'{100 * cut(m, x):.0f}' for x in K) for m in M))
wpk = {m: max(r['fleet']['wing']['max'] for r in cc(m, 'A2', 'N2', 'k', 1)) for m in M}
chk('C8', all(wpk[m] <= 24 for m in M), '; '.join(f'{m} largest Wing peak {wpk[m]} (filed 24)' for m in M))
# ---- table
L = ['# CAPACITY1 results table (generated by planned/capacity1_analyze.py)', '', f'{sum(ok for _, ok, _ in P)} of {len(P)} predictions passed. Rows: {len(R)}.', '']
L += [f'- {"PASS" if ok else "FAIL"} {n}: {t}' for n, ok, t in P]
L += ['', '## Capacity (highest k with overall held <= 10 % and every company <= 25 %; 0 = none)', '', '| Layout | Houston | DFW |', '|---|---|---|']
L += [f'| {h} / {v} | {cap[("houston", h, v)]} | {cap[("dfw", h, v)]} |' for h, v in CFG]
L += ['', '## Held share by traffic (seeds 1-3; all / Wing / Zipline / Amazon; flights checked)', '', '| Metro | Layout | k | All | Wing | Zipline | Amazon | Checked | Cancelled | Mean delay s |', '|---|---|---|---|---|---|---|---|---|---|']
for m in M:
    for h, v in CFG:
        for x in K:
            rows = cc(m, h, v, 'k', x); n = sum(r['cost']['all']['n'] for r in rows); dl = sum(r['cost']['all']['delayed'] for r in rows)
            L.append(f'| {m} | {h} / {v} | {x} | ' + ' | '.join(pc(held(rows, op)) for op in ('all',) + OPS) + f' | {n} | {sum(r["cost"]["all"]["cancelled"] for r in rows)} | {round(sum(r["cost"]["all"]["sumD"] for r in rows) / dl) if dl else 0} |')
L += ['', '## Build-out vs utilisation at matched traffic (overall held share)', '', '| Metro | Layout | Share | Fewer sites (f) | All sites quieter (k) |', '|---|---|---|---|---|']
L += [f'| {m} | {h} / N2 | {f} | {pc(held(cc(m, h, "N2", "f", f)))} | {pc(held(cc(m, h, "N2", "k", f)))} |' for m in M for h in ('A0', 'A2') for f in (0.25, 0.5)]
L += ['', '## Without sharing: between-company meetings (30 m / 10 m, seeds 1-3)', '', '| Metro | k | S1 | A2 | Cut | Flights (A2) | A2 meetings per 1,000 flights |', '|---|---|---|---|---|---|---|']
for m in M:
    for x in K:
        fl = sum(r['flights'] for r in U if r['metro'] == m and r['arm'] == 'A2' and r['x'] == x)
        L.append(f'| {m} | {x} | {bw(m, "S1", x)} | {bw(m, "A2", x)} | {100 * cut(m, x):.0f} % | {fl} | {1000 * bw(m, "A2", x) / fl:.2f} |' if fl else f'| {m} | {x} | - | - | - | - | - |')
L += ['', '## Fleet: most aircraft in the air at once at one site (no turnaround; A2 / N2 runs, max over seeds)', '', '| Metro | k | Wing max (filed 24) | Wing median site | Zipline max | Zipline median site | Amazon max |', '|---|---|---|---|---|---|---|']
for m in M:
    for x in K:
        rows = cc(m, 'A2', 'N2', 'k', x); g = lambda op, q: max(r['fleet'][op][q] for r in rows) if rows else '-'
        L.append(f'| {m} | {x} | {g("wing", "max")} | {g("wing", "median")} | {g("zipline", "max")} | {g("zipline", "median")} | {g("amazon", "max")} |')
open('planned/capacity1_results_table.md', 'w').write('\n'.join(L) + '\n')
print(f'{sum(ok for _, ok, _ in P)} of {len(P)} passed')

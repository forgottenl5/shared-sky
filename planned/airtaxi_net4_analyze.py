#!/usr/bin/env python3
"""AIRTAXI_NET4 analysis (registration planned/AIRTAXI_NET4_PREREG.md). Reads out/airtaxi_net4_*.json, prints verdicts and writes
planned/airtaxi_net4_results_table.md."""
import json, glob, statistics as st
rows = [r for f in sorted(glob.glob('out/airtaxi_net4_*.json')) for r in json.load(open(f))]
drive = {}
for ln in open('taxi/data/drive_times_raw.tsv'):
    if not ln.strip() or ln.startswith('#') or ln.startswith('from'): continue
    a, b, t, lo, hi = ln.rstrip('\n').split('\t')[:5]; a = 'DFWc' if a == 'DFW' else a; b = 'DFWc' if b == 'DFW' else b
    drive[(a, b, t)] = (float(lo) + float(hi)) / 2
ROUTES = {'DFW': [('AFW', 'DFWc'), ('AFW', 'TOY'), ('DFWc', 'TOY'), ('DFWc', '49T')], 'HOU': [('IAH', 'HOU'), ('IAH', 'EFD')]}
NET1 = {'AFW-DFWc': 32.1, 'AFW-TOY': 44.5, 'DFWc-TOY': 20.0, 'DFWc-49T': 27.6, 'IAH-HOU': 30.3, 'IAH-EFD': 31.0}
PEAK = ('08:00', '17:30')
P, L = [], []
def chk(name, ok, txt): P.append((name, ok, txt)); print(('PASS' if ok else 'FAIL'), name, txt)
# ---- Part A
A = {}
for m, routes in ROUTES.items():
    rs = [r for r in rows if r['part'] == 'A' and r['metro'] == m]
    for a, b in routes:
        per = []
        for r in rs:
            v = []
            for x, y in ((a, b), (b, a)):
                T = r['ods'][f'{x}>{y}'][2] / 60
                for t in PEAK: v.append(drive[(x, y, t)] - T)
            per.append(sum(v) / len(v))
        A[f'{a}-{b}'] = (st.median(per), min(per), max(per), len(per))
d = {k: A[k][0] - NET1[k] for k in A}
chk('A1', all(abs(x) <= 1.0 for x in d.values()) and len(A) == 6, 'E*(v5) - E*(NET1): ' + ', '.join(f'{k} {v:+.1f}' for k, v in d.items()))
rank = sorted(A, key=lambda k: -A[k][0]); chk('A2', rank[0] == 'AFW-TOY' and rank[-1] == 'DFWc-TOY', f'highest {rank[0]} ({A[rank[0]][0]:.1f}), lowest {rank[-1]} ({A[rank[-1]][0]:.1f})')
# ---- Part B
def B(m, U):
    out = {}
    for T in sorted({r['T'] for r in rows if r['part'] == 'B' and r['metro'] == m}):
        rs = [r for r in rows if r['part'] == 'B' and r['metro'] == m and r['U'] == U and r['T'] == T]
        if not rs: continue
        fl = [r['fleet'] if r['fleet'] is not None else 999 for r in rs]
        out[T] = dict(n=len(rs), median=st.median(fl), lo=min(fl), hi=max(fl), reached=sum(1 for r in rs if r['fleet'] is not None),
                      infeas=st.mean(r['at']['infeasible'] / r['at']['n'] for r in rs), dead=st.median(r['at']['deadShare'] for r in rs),
                      wait=st.median((r['at']['medWait'] or 0) / 60 for r in rs), pairs=sorted({p for r in rs for p in r['at']['infeasPairs']}),
                      fleets=fl, held=max(max(r['at']['maxHeld'].values()) for r in rs))
    return out
BD, BH, BH144 = B('DFW', 100), B('HOU', 100), B('HOU', 144)
rng = {12: (10, 18), 24: (18, 30), 48: (34, 56)}
chk('B1', all(rng[T][0] <= BD[T]['median'] <= rng[T][1] for T in rng), 'DFW U100 median fleet: ' + ', '.join(f"{T}/h {BD[T]['median']} ({BD[T]['lo']}-{BD[T]['hi']})" for T in rng))
chk('B2', sum(1 for f in BD[24]['fleets'] if f > 14) >= 8, f"seeds needing more than 14 at 24/h: {sum(1 for f in BD[24]['fleets'] if f > 14)} of {len(BD[24]['fleets'])}")
inf100 = st.mean(BH[T]['infeas'] for T in BH); p100 = sorted({p for T in BH for p in BH[T]['pairs']}); p144 = sorted({p for T in BH144 for p in BH144[T]['pairs']})
chk('B3', p100 == ['GLS-IAH', 'GLS-SGR'] and 0.28 <= inf100 <= 0.32 and p144 == [], f'U100 infeasible pairs {p100}, share {inf100:.3f}; U144 {p144}')
rh = {6: (4, 9), 12: (7, 14), 24: (12, 24)}
chk('B4', all(rh[T][0] <= BH[T]['median'] <= rh[T][1] for T in rh) and all(BH144[T]['median'] > BH[T]['median'] for T in rh),
    'HOU median fleet U100 / U144: ' + ', '.join(f"{T}/h {BH[T]['median']} / {BH144[T]['median']}" for T in rh))
chk('B5', BD[24]['dead'] >= 0.15, f"DFW 24/h empty repositioning share {BD[24]['dead']:.3f}")
npass = sum(1 for _, ok, _ in P if ok); print(f'{npass} of {len(P)} passed')
L = ['# AIRTAXI_NET4 results table (generated by planned/airtaxi_net4_analyze.py)', '', f'{npass} of {len(P)} predictions passed.', '']
L += [f'- {"PASS" if ok else "FAIL"} {n}: {t}' for n, ok, t in P]
L += ['', '## Part A: break-even access time E* at peak, engine v5 vs NET1 (minutes; median over 10 seeds, range)', '', '| Route | v5 | NET1 (v2 recheck) | difference |', '|---|---|---|---|']
L += [f'| {k} | {v[0]:.1f} ({v[1]:.1f}-{v[2]:.1f}) | {NET1[k]:.1f} | {v[0] - NET1[k]:+.1f} |' for k, v in A.items()]
for name, X in (('DFW, U100', BD), ('Houston, U100', BH), ('Houston, U144 (sensitivity)', BH144)):
    L += ['', f'## Part B: Archer network, {name}', '', '| Trips/h | Fleet median (range), seeds reaching | Infeasible share | Empty repositioning share | Median wait (min) | Most stands held at one site |', '|---|---|---|---|---|---|']
    L += [f"| {T} | {v['median']} ({v['lo']}-{v['hi']}), {v['reached']}/{v['n']} | {v['infeas']:.3f} | {v['dead']:.3f} | {v['wait']:.1f} | {v['held']} |" for T, v in X.items()]
L += ['', '999 = not reached within the fleet list or the stand limit.']
open('planned/airtaxi_net4_results_table.md', 'w').write('\n'.join(L) + '\n'); print('wrote planned/airtaxi_net4_results_table.md')

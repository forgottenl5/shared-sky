"""UNCERT1 analysis: percentiles, Spearman ranks, predictions U1-U6, table. Usage: python3 -I planned/uncert1_analyze.py"""
import json, glob, numpy as np, pandas as pd
A = json.load(open('out/uncert1_access.json')); DRF = json.load(open('planned/uncert1_draws.json'))['fleet']
K2 = json.load(open('out/uncert1_k2.json')); FR = [x for f in sorted(glob.glob('out/uncert1_fleet_[0-9].json')) for x in json.load(open(f))]
A1 = json.load(open('out/access1b_v1.json'))
res = []
def add(n, ok, d): res.append((n, ok, d)); print(('PASS ' if ok else 'FAIL ') + n, d)
def pc(v): return {p: float(np.percentile(v, p)) for p in (5, 25, 50, 75, 95)}
def sp(df, y): return {c: float(df[c].rank().corr(df[y].rank())) for c in df.columns if c != y}
L = ['# UNCERT1 results table (generated by planned/uncert1_analyze.py)\n']
# access
acc = {}
for m in ('DFW', 'HOU'):
    df = pd.DataFrame({**A['draws'], 'y': A['share'][m]}); acc[m] = (pc(df['y']), sp(df, 'y'), A1['metros'][m]['scen']['peak_P20_T10']['share'])
    L += [f"\n## Access share, {m} (12 sites, peak, >= 10 min saved; registered point {100*acc[m][2]:.2f} %)\n", '| percentile | share % |', '|---|---|'] + [f'| {p} | {100*v:.2f} |' for p, v in acc[m][0].items()]
    L.append('\nSpearman with each input: ' + ', '.join(f'{k} {v:+.2f}' for k, v in acc[m][1].items()))
add('U1 access p95/p05 >= 5', all(acc[m][0][95] / acc[m][0][5] >= 5 for m in acc), {m: round(acc[m][0][95] / acc[m][0][5], 1) for m in acc})
add('U2 f has the largest |Spearman| (access)', all(max(acc[m][1], key=lambda k: abs(acc[m][1][k])) == 'f' for m in acc), {m: {k: round(v, 2) for k, v in acc[m][1].items()} for m in acc})
add('U3 registered point above the 75th percentile', all(acc[m][2] > acc[m][0][75] for m in acc), {m: (round(100 * acc[m][2], 2), round(100 * acc[m][0][75], 2)) for m in acc})
# fleet
cells = {}
for m in ('DFW', 'HOU'):
    for r in (3, 6):
        rows = [x for x in FR if x['metro'] == m and x['r'] == r]; rows.sort(key=lambda x: x['i'])
        df = pd.DataFrame([{**x['v'], 'y': x['fleet']} for x in rows]); ref = next(k['median'] for k in K2 if k['metro'] == m and k['r'] == r)
        cells[(m, r)] = (pc(df['y']), sp(df, 'y'), ref)
        L += [f"\n## Required fleet, {m}, r = {r} (reference at registered inputs: {ref})\n", '| percentile | fleet |', '|---|---|'] + [f'| {p} | {v:.1f} |' for p, v in cells[(m, r)][0].items()]
        L.append('\nSpearman: ' + ', '.join(f'{k} {v:+.2f}' for k, v in cells[(m, r)][1].items()))
add('U4 fleet p95/p05 <= 1.6 at r = 3', all(cells[(m, 3)][0][95] / cells[(m, 3)][0][5] <= 1.6 for m in ('DFW', 'HOU')), {m: round(cells[(m, 3)][0][95] / cells[(m, 3)][0][5], 2) for m in ('DFW', 'HOU')})
add('U5 charge rate has the largest |Spearman| (fleet, 4 cells)', all(max(c[1], key=lambda k: abs(c[1][k])) == 'charge' for c in cells.values()), {f'{k[0]} r{k[1]}': {a: round(b, 2) for a, b in c[1].items()} for k, c in cells.items()})
add('U6 reference fleet within p5-p95 (4 cells)', all(c[0][5] <= c[2] <= c[0][95] for c in cells.values()), {f'{k[0]} r{k[1]}': (c[2], round(c[0][5], 1), round(c[0][95], 1)) for k, c in cells.items()})
n = sum(1 for x in res if x[1]); print(f'\n{n} of 6 predictions passed')
print('K2 reference fleets', {f"{k['metro']} r{k['r']}": k['median'] for k in K2})
L.append('\n## Predictions\n'); L += [f"- {'PASS' if ok else 'FAIL'} {a}: {b}" for a, ok, b in res]
open('planned/uncert1_results_table.md', 'w').write('\n'.join(L) + '\n')

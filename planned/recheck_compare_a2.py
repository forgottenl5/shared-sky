#!/usr/bin/env python3
"""RECHECK_A2 analysis (planned/RECHECK_A2_PREREG.md). Written and committed before the re-check runs.

Runs the COUNTFIX and RECOUNT1 analysis scripts, unchanged, in the repo root (original runs) and in the re-check shadow root
(fixes on; the shadow has its own copy of planned/, so the scripts' own output files are written there). Pairs verdict rows in
order, tabulates pooled counts per cell and scores Q1-Q3.
Usage: python3 planned/recheck_compare_a2.py <shadow root>   (from the repo root) -> markdown on stdout
"""
import glob, json, os, re, subprocess, sys
from collections import defaultdict

REPO = os.getcwd(); NEW = os.path.abspath(sys.argv[1])
ROW = re.compile(r"^\| *(U[1-4]|K1|R[1-3])\b")
def verdicts(root, script):
    out = subprocess.run([sys.executable, f"planned/{script}"], cwd=root, capture_output=True, text=True).stdout
    return [(l.strip(), re.findall(r"\b(PASS|FAIL)\b", l)) for l in out.splitlines() if ROW.match(l)]

def countfix(root):
    c = defaultdict(lambda: [0, 0, 0, 0])
    for f in glob.glob(os.path.join(root, "out/countfix/*.json")):
        r = json.load(open(f)); k = (r["job"], r["arm"]); c[k][0] += r["cross_wide"]; c[k][1] += r["cross_close"]; c[k][2] += r["events"]; c[k][3] += 1
    return c
def recount(root):
    c = defaultdict(lambda: [0, 0, 0, 0])
    for name in ("out/recount1_sub1_22-24.json", "out/recount1_sub4_22-31.json"):
        p = os.path.join(root, name)
        if not os.path.exists(p): continue
        for r in json.load(open(p)): k = (f"sub {r['sub']}", r["arm"]); c[k][0] += r["cross_wide"]; c[k][1] += r["cross_close"]; c[k][2] += r["holds"]; c[k][3] += 1
    return c

P = print
P("# RECHECK_A2 results table (generated by planned/recheck_compare_a2.py)\n")
flips, total, q1, q2 = [], 0, [], []
for S, script, cells, devcell in (("COUNTFIX", "countfix_analyze.py", countfix, lambda k: k[0] in ("dev", "rth")),
                                  ("RECOUNT1", "recount1_analyze.py", recount, lambda k: True)):
    old, new = verdicts(REPO, script), verdicts(NEW, script)
    P(f"## {S}\n"); P("| # | verdict row (re-check run) | original | re-check |"); P("|---|---|---|---|")
    if len(old) != len(new): P(f"| — | ROW COUNT DIFFERS: {len(old)} vs {len(new)} | | |")
    for i, ((lo, vo), (ln, vn)) in enumerate(zip(old, new), 1):
        pred = not ln.startswith("| K"); total += pred; ch = vo != vn
        if ch and pred: flips.append((S, ln))
        P(f"| {i} | {ln[:170].replace('|', '/')} | {'/'.join(vo)} | {'/'.join(vn)}{' **CHANGED**' if ch else ''}{'' if pred else ' (check, not a prediction)'} |")
    co, cn = cells(REPO), cells(NEW)
    P("\n| cell | runs | wide original → re-check | change | close original → re-check | events original → re-check |"); P("|---|---|---|---|---|---|")
    for k in sorted(co):
        a, b = co[k], cn.get(k, [0, 0, 0, 0]); chg = None if a[0] == 0 else (b[0] - a[0]) / a[0]
        if S == "RECOUNT1" and k[0] == "sub 1": pass   # reported only: at 1 check/s the hover point moves by half a second of flight
        elif devcell(k):
            if a[0] >= 10: q2.append((S, k, a[0], b[0]))
        elif a[0] >= 20: q1.append((S, k, a[0], b[0], chg))
        P(f"| {' '.join(k)} | {a[3]} / {b[3]} | {a[0]} → {b[0]} | {'—' if chg is None else f'{100 * chg:+.1f} %'} | {a[1]} → {b[1]} | {a[2]} → {b[2]} |")
    P("")
P("## Registered predictions\n")
ok1 = len(q1) > 0 and all(abs(c) <= 0.06 for *_, c in q1)
P(f"- **Q1** (COUNTFIX cells without deviations, original wide >= 20: within ±6 %): {len(q1)} cells, largest change {max((abs(c) for *_, c in q1), default=0) * 100:.1f} %. {'**PASS**' if ok1 else '**FAIL**'}")
up = sum(1 for *_, a, b in q2 if b >= a); ok2 = len(q2) > 0 and up * 3 >= 2 * len(q2)
P(f"- **Q2** (deviation cells counted 4 times per second, original wide >= 10: re-check >= original in at least two thirds): {up} of {len(q2)}. {'**PASS**' if ok2 else '**FAIL**'}")
P(f"- **Q3** (at most 2 of the {total} original prediction verdicts change): {len(flips)} changed. {'**PASS**' if len(flips) <= 2 else '**FAIL**'}")
for S, l in flips: P(f"  - {S}: {l[:200]}")

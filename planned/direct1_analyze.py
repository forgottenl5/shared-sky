#!/usr/bin/env python3
"""DIRECT1 analysis (planned/DIRECT1_PREREG.md). References from INTENT2 (cost, risk) and CURVE1 (cut); risk formula as INTENT2."""
import json, glob, math
rd = lambda p: [json.loads(l) for f in glob.glob(p) for l in open(f) if l.strip()]
NEW = rd('out/direct1/*.jsonl'); I2 = rd('out/intent2/*.jsonl'); C1 = [r for r in rd('out/curve1/*.jsonl') if r['seed'] <= 5]
R = NEW + I2; U = [r for r in NEW if r['part'] == 'u'] + C1
M, VT = ('houston', 'dfw'), [5, 7.5, 10, 12.5, 15, 20]
LV = {'L1': (3, 4), 'L2': (8, 13)}; K_RAD = math.sqrt(-2 * math.log(0.05)); K_VER = 1.96; WING = (0.65, 0.25); BIG = (1.5, 0.3)
Phi = lambda x: 0.5 * (1 + math.erf(x / math.sqrt(2)))
def band(d, W, s): return Phi((W - d) / s) - Phi((-W - d) / s) if s > 0 else (1.0 if abs(d) < W else 0.0)
size = lambda op: WING if op == 'wing' else BIG
def expected(row, lv):
    h95, v95 = LV[lv]; sh = math.sqrt(2) * h95 / K_RAD; sz = math.sqrt(2) * v95 / K_VER; p = 0.0
    for opA, opB, dperp, dz, dh, vrel in row['enc']: A, B = size(opA), size(opB); p += band(dperp, A[0] + B[0], sh) * band(dz, A[1] + B[1], sz)
    return p
LVL = {'N1': 'L1', 'N2': 'L2'}
def rr(m, a, c): return [r for r in R if r['part'] == 'r' and r['metro'] == m and r['arm'] == a and r['check'] == c]
def rate(m, a, c, lv=None): x = rr(m, a, c); lv = lv or LVL[c]; return 1e5 * sum(expected(r, lv) for r in x) / sum(r['flightHours'] for r in x)
def cc(m, h, v): return [r for r in R if r['part'] == 'c' and r['metro'] == m and r['heights'] == h and r['vol'] == v]
def held(rows, op='all'):
    n = sum(r['cost'][op]['n'] for r in rows if op in r['cost']); return sum(r['cost'][op]['delayed'] + r['cost'][op]['cancelled'] for r in rows if op in r['cost']) / n if n else float('nan')
Hd = lambda m, h, v, op='all': held(cc(m, h, v), op)
def ut(m, a, v): return sum(r['counts'][f'h30v{v:g}'] for r in U if r['metro'] == m and r['arm'] == a)
def cut(m, a, v): return 1 - ut(m, a, v) / ut(m, 'S1', v)
P = []
def chk(n, ok, t): P.append((n, ok, t)); print('PASS' if ok else 'FAIL', n, t)
chk('E1', all(Hd(m, 'D2', 'N2') > Hd(m, 'A2', 'N2') for m in M), '; '.join(f'{m} N2 D2 {100 * Hd(m, "D2", "N2"):.1f} vs A2 {100 * Hd(m, "A2", "N2"):.1f} %' for m in M))
chk('E2', all(Hd(m, 'D4', 'N2') > Hd(m, 'D2', 'N2') for m in M), '; '.join(f'{m} N2 D4 {100 * Hd(m, "D4", "N2"):.1f} vs D2 {100 * Hd(m, "D2", "N2"):.1f} %' for m in M))
chk('E3', all(Hd(m, 'DD', 'N2') > Hd(m, 'A2', 'N2') for m in M), '; '.join(f'{m} N2 DD {100 * Hd(m, "DD", "N2"):.1f} vs A2 {100 * Hd(m, "A2", "N2"):.1f} %' for m in M))
chk('E4', all(rate(m, 'D2', 'N2') < rate(m, 'FLEX', 'N2') for m in M), '; '.join(f'{m} N2 D2 {rate(m, "D2", "N2"):.3g} vs FLEX {rate(m, "FLEX", "N2"):.3g}' for m in M))
chk('E5', all(cut(m, 'D2', 10) >= 0.5 for m in M), '; '.join(f'{m} D2 cut {100 * cut(m, "D2", 10):.0f} %' for m in M))
npass = sum(1 for _, ok, _ in P if ok)
sp = {r['metro']: r['split'] for r in NEW}
L = ['# DIRECT1 results table (generated by planned/direct1_analyze.py)', '', f'{npass} of {len(P)} predictions passed. New rows: {len(NEW)}. Median leg (DD split): ' + ', '.join(f'{m} {v:.0f} m' for m, v in sp.items()), ''] + [f'- {"PASS" if ok else "FAIL"} {n}: {t}' for n, ok, t in P]
L += ['', '## Held share (windy hours, seeds 1-5)', '', '| Metro | Layout | Size | Held | Wing | Zipline | Amazon |', '|---|---|---|---|---|---|---|']
for m in M:
    for h in ('A0', 'A2', 'M1', 'FLEX', 'D2', 'D4', 'DD'):
        for v in ('N1', 'N2'):
            x = cc(m, h, v); L.append(f'| {m} | {h} | {v} | {100 * held(x):.1f} % | {100 * held(x, "wing"):.1f} % | {100 * held(x, "zipline"):.1f} % | {100 * held(x, "amazon"):.1f} % |')
L += ['', '## Residual collision risk per 100,000 flight hours (still air)', '', '| Metro | Layout | No check (L2) | N1 (L1) | N2 (L2) |', '|---|---|---|---|---|']
for m in M:
    for a in ('A0', 'A2', 'M1', 'FLEX', 'D2', 'D4', 'DD'): L.append(f'| {m} | {a} | {rate(m, a, "NONE", "L2"):.3g} | {rate(m, a, "N1"):.3g} | {rate(m, a, "N2"):.3g} |')
L += ['', '## Cut against S1 without plan sharing (30 m sideways; seeds 1-5)', '', '| Metro | Layout | ' + ' | '.join(f'{v:g} m' for v in VT) + ' |', '|---|---|' + '---|' * len(VT)]
for m in M:
    for a in ('A2', 'D2', 'D4', 'DD'): L.append(f'| {m} | {a} | ' + ' | '.join(f'{100 * cut(m, a, v):.0f} %' for v in VT) + ' |')
open('planned/direct1_results_table.md', 'w').write('\n'.join(L) + '\n'); print(f'{npass} of {len(P)} passed')

#!/usr/bin/env python3
"""LAYOUT1 analysis (planned/LAYOUT1_PREREG.md). References from CURVE1 (S1, A2), COORD1 + SEEDS2 (A0, A2) and RISK1 + RISK2 (S1, A2)."""
import glob, json, math, random
rd = lambda pat: [json.loads(l) for f in sorted(glob.glob(pat)) for l in open(f) if l.strip()]
NEW = rd('out/layout1/*.jsonl'); U = [r for r in NEW if r['part'] == 'u'] + rd('out/curve1/*.jsonl'); C = [r for r in NEW if r['part'] == 'c'] + rd('out/coord1/*.jsonl') + rd('out/seeds2/*.jsonl')
R1 = rd('out/risk1/*.jsonl')
for r in R1: r['check'] = 'NONE'
RR = [r for r in NEW if r['part'] == 'r'] + R1 + rd('out/risk2/*.jsonl')
M, VT = ('houston', 'dfw'), [5, 7.5, 10, 12.5, 15, 20]
# U
def ut(m, a, v, seeds=None): return sum(r['counts'][f'h30v{v:g}'] for r in U if r['metro'] == m and r['arm'] == a and (seeds is None or r['seed'] in seeds))
def ucut(m, a, v, seeds=None): s = ut(m, 'S1', v, seeds); return 1 - ut(m, a, v, seeds) / s
# C (pooled, as SEEDS2; seeds 1-10)
def crow(m, h, arm): return [r for r in C if r['metro'] == m and r['heights'] == h and r['arm'] == arm and 1 <= r['seed'] <= 10]
def held(m, h, op='all', seeds=None):
    x = [r for r in crow(m, h, 'V2') if seeds is None or r['seed'] in seeds]; n = sum(r['cost'][op]['n'] for r in x if op in r['cost']); return sum(r['cost'][op]['delayed'] for r in x if op in r['cost']) / n if n else float('nan')
def cwide(m, h, arm): return sum(r['wide'] for r in crow(m, h, arm))
# R (RISK2 formula, unchanged)
LV = {'L2': (8, 13)}; K_RAD = math.sqrt(-2 * math.log(0.05)); K_VER = 1.96; WING = (0.65, 0.25); BIG = (1.5, 0.3)
Phi = lambda x: 0.5 * (1 + math.erf(x / math.sqrt(2)))
def band(d, W, s): return Phi((W - d) / s) - Phi((-W - d) / s) if s > 0 else (1.0 if abs(d) < W else 0.0)
size = lambda op: WING if op == 'wing' else BIG
def expected(row, lv='L2', rho=0):
    h95, v95 = LV[lv]; f = math.sqrt(1 - rho); sh = math.sqrt(2) * f * h95 / K_RAD; sz = math.sqrt(2) * f * v95 / K_VER; p = 0.0
    for opA, opB, dperp, dz, dh, vrel in row['enc']: A, B = size(opA), size(opB); p += band(dperp, A[0] + B[0], sh) * band(dz, A[1] + B[1], sz)
    return p
def rrows(m, a, c): return [r for r in RR if r['metro'] == m and r['arm'] == a and r['check'] == c]
def rate(m, a, c): x = rrows(m, a, c); return 1e5 * sum(expected(r) for r in x) / sum(r['flightHours'] for r in x)
P = []
def chk(n, ok, t): P.append((n, ok, t)); print('PASS' if ok else 'FAIL', n, t)
chk('U1', all(ucut(m, 'M1', v) >= 0.75 for m in M for v in VT), '; '.join(f'{m} ' + ' / '.join(f'{100 * ucut(m, "M1", v):.0f}' for v in VT) + ' %' for m in M))
chk('U2', all(ucut(m, 'M1', 10) > ucut(m, 'M2', 10) for m in M), '; '.join(f'{m} M1 {100 * ucut(m, "M1", 10):.0f} % vs M2 {100 * ucut(m, "M2", 10):.0f} %' for m in M))
chk('C1', all(held(m, 'M1') <= 0.10 for m in M), '; '.join(f'{m} {100 * held(m, "M1"):.1f} %' for m in M))
chk('C2', all(held(m, 'M1', 'amazon') <= 0.60 for m in M), '; '.join(f'{m} {100 * held(m, "M1", "amazon"):.1f} %' for m in M))
c3 = {(m, h): 1 - cwide(m, h, 'V2') / cwide(m, h, 'NONE') for m in M for h in ('M1', 'M2')}
chk('C3', all(v >= 0.99 for v in c3.values()), '; '.join(f'{m} {h} {100 * v:.1f} %' for (m, h), v in c3.items()))
chk('R1', all(rate(m, 'M1', 'V2') < rate(m, 'A2', 'V2') for m in M), '; '.join(f'{m} M1 {rate(m, "M1", "V2"):.3g} vs A2 {rate(m, "A2", "V2"):.3g}' for m in M))
chk('R2', all(rate(m, 'M1', 'V2') <= rate(m, 'S1', 'V2') for m in M), '; '.join(f'{m} M1 {rate(m, "M1", "V2"):.3g} vs S1 {rate(m, "S1", "V2"):.3g}' for m in M))
npass = sum(1 for _, ok, _ in P if ok)
def boot(f, B=2000):
    seeds = list(range(1, 11)); g = random.Random(11); v = sorted(f([g.choice(seeds) for _ in seeds]) for _ in range(B)); return v[int(0.025 * B)], v[int(0.975 * B) - 1]
def multi(fn):  # resample seeds with multiplicity by summing per-seed values
    return lambda s: fn(s)
L = ['# LAYOUT1 results table (generated by planned/layout1_analyze.py)', '', f'{npass} of {len(P)} predictions passed. Rows: {len(NEW)} new.', ''] + [f'- {"PASS" if ok else "FAIL"} {n}: {t}' for n, ok, t in P]
L += ['', '## U: cut against S1 without plan sharing (30 m horizontal)', '', '| Metro | Layout | ' + ' | '.join(f'{v:g} m' for v in VT) + ' |', '|---|---|' + '---|' * len(VT)]
for m in M:
    for a in ('A2', 'M1', 'M2'): L.append(f'| {m} | {a} | ' + ' | '.join(f'{100 * ucut(m, a, v):.0f} %' for v in VT) + ' |')
L += ['', 'Planned conflicts per hour at 30 m / 10 m (pooled, 20 measured hours): ' + '; '.join(f'{m} ' + ', '.join(f'{a} {ut(m, a, 10) / 20:.1f}' for a in ('S1', 'A2', 'M1', 'M2')) for m in M)]
for m in M:
    for a in ('M1', 'M2'):
        pr = {}
        for r in U:
            if r['metro'] == m and r['arm'] == a:
                for p, c in r['pairs'].get('h30v10', {}).items(): pr[p] = pr.get(p, 0) + c
        L.append(f'- {m} {a} company pairs at 30 m / 10 m: {pr}')
L += ['', '## C: held by the plan check V2 (10 windy hours, seeds 1-10)', '', '| Metro | Heights | Held (all) | 95 % interval | Wing | Zipline | Amazon | Mean delay (min) | V2 removes |', '|---|---|---|---|---|---|---|---|---|']
for m in M:
    for h in ('A0', 'A2', 'M1', 'M2'):
        x = crow(m, h, 'V2'); d = sum(r['cost']['all']['delayed'] for r in x); md = sum(r['cost']['all']['meanD'] * r['cost']['all']['delayed'] for r in x) / d / 60 if d else float('nan')
        lo, hi = boot(lambda s: sum(r['cost']['all']['delayed'] for k in s for r in crow(m, h, 'V2') if r['seed'] == k) / sum(r['cost']['all']['n'] for k in s for r in crow(m, h, 'V2') if r['seed'] == k))
        rm = 1 - cwide(m, h, 'V2') / cwide(m, h, 'NONE') if cwide(m, h, 'NONE') else float('nan')
        L.append(f'| {m} | {h} | {100 * held(m, h):.1f} % | {100 * lo:.1f}-{100 * hi:.1f} | {100 * held(m, h, "wing"):.1f} % | {100 * held(m, h, "zipline"):.1f} % | {100 * held(m, h, "amazon"):.1f} % | {md:.1f} | {100 * rm:.1f} % |')
L += ['', '## R: expected collisions per 100,000 flight hours at average GPS error (L2)', '', '| Metro | Heights | No check | V2 | Removed by V2 | Held by V2 (still air) |', '|---|---|---|---|---|---|']
for m in M:
    for a in ('S1', 'A2', 'M1', 'M2'):
        x = rrows(m, a, 'V2'); n = sum(r['checked'] for r in x); dl = sum(r['delayed'] for r in x)
        r0, r2 = rate(m, a, 'NONE'), rate(m, a, 'V2')
        L.append(f'| {m} | {a} | {r0:.3g} | {r2:.3g} | {100 * (1 - r2 / r0) if r0 else float("nan"):.0f} % | {100 * dl / n:.1f} % |')
open('planned/layout1_results_table.md', 'w').write('\n'.join(L) + '\n'); print(f'{npass} of {len(P)} passed')

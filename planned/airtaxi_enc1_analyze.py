#!/usr/bin/env python3
"""AIRTAXI_ENC1 analysis (registration planned/AIRTAXI_ENC1_PREREG.md). Reads out/airtaxi_enc1/*.jsonl."""
import json, glob
R = [json.loads(l) for f in glob.glob('out/airtaxi_enc1/*.jsonl') for l in open(f) if l.strip()]
H = 12; P = []
def chk(n, ok, t): P.append((n, ok, t)); print('PASS' if ok else 'FAIL', n, t)
def rows(m, lv): return [r for r in R if r['metro'] == m and r['level'] == lv]
def mean(m, lv, arm, e, ph): x = rows(m, lv); return sum(r[arm]['ep'][e][ph] for r in x) / len(x) / H
MET = ('DFW', 'HOU'); NM = {'DFW': 'DFW', 'HOU': 'Houston'}
s1 = {(r['metro'], r['level']): r for r in R if r['seed'] == 1}
chk('X1', all(s1[(m, lv)]['A']['ep']['E2']['en'] >= 1 for m in MET for lv in (1, 2, 3)), ', '.join(f"{NM[m]} L{lv} {s1[(m, lv)]['A']['ep']['E2']['en']}" for m in MET for lv in (1, 2, 3)))
band = {'DFW': (6, 20), 'HOU': (4, 14)}
chk('X2', all(band[m][0] <= mean(m, 2, 'A', 'E1', 'en') <= band[m][1] for m in MET), ', '.join(f"{NM[m]} {mean(m, 2, 'A', 'E1', 'en'):.1f}/h" for m in MET))
ratio = {m: mean(m, 3, 'A', 'E1', 'en') / max(1e-9, mean(m, 1, 'A', 'E1', 'en')) for m in MET}
chk('X3', all(8 <= ratio[m] <= 24 for m in MET), ', '.join(f"{NM[m]} {ratio[m]:.1f}x" for m in MET))
tr = {m: mean(m, 2, 'A', 'E1', 'term') / max(1e-9, mean(m, 2, 'A', 'E1', 'en')) for m in MET}
chk('X4', all(0.5 <= tr[m] <= 3 for m in MET), ', '.join(f"{NM[m]} terminal {mean(m, 2, 'A', 'E1', 'term'):.1f}/h = {tr[m]:.2f}x en route" for m in MET))
cut = {(m, lv): 1 - mean(m, lv, 'B', 'E1', 'en') / max(1e-9, mean(m, lv, 'A', 'E1', 'en')) for m in MET for lv in (1, 2, 3)}
e2b = sum(r['B']['ep']['E2']['en'] for r in R)
chk('X5', all(v >= 0.8 for v in cut.values()) and e2b == 0, ', '.join(f"{NM[m]} L{lv} {100 * cut[(m, lv)]:.0f} %" for m, lv in cut) + f"; arm B en-route E2 total {e2b}")
tc = {m: 1 - mean(m, 2, 'B', 'E1', 'term') / max(1e-9, mean(m, 2, 'A', 'E1', 'term')) for m in MET}
chk('X6', all(tc[m] < 0.5 for m in MET), ', '.join(f"{NM[m]} terminal cut {100 * tc[m]:.0f} %" for m in MET))
n = sum(1 for _, ok, _ in P if ok)
L = ['# AIRTAXI_ENC1 results table (generated by planned/airtaxi_enc1_analyze.py)', '', f'{n} of {len(P)} predictions passed. Runs: {len(R)}.', ''] + [f'- {"PASS" if ok else "FAIL"} {a}: {t}' for a, ok, t in P]
L += ['', 'Seed means, per hour over 12 measured hours.', '', '| Metro | Level | Arm | E1 en route | E1 terminal | E2 en route | E2 terminal | Minutes with 2+ holding at one site, per hour |', '|---|---|---|---|---|---|---|---|']
for m in MET:
    for lv in (1, 2, 3):
        for arm in ('A', 'B'):
            x = rows(m, lv); mh = sum(r[arm]['multiHoldMinutes'] for r in x) / len(x) / H
            L.append(f"| {NM[m]} | {lv} | {arm} | {mean(m, lv, arm, 'E1', 'en'):.2f} | {mean(m, lv, arm, 'E1', 'term'):.2f} | {mean(m, lv, arm, 'E2', 'en'):.2f} | {mean(m, lv, arm, 'E2', 'term'):.2f} | {mh:.2f} |")
open('planned/airtaxi_enc1_results_table.md', 'w').write('\n'.join(L) + '\n'); print(f'{n} of {len(P)} passed; wrote planned/airtaxi_enc1_results_table.md')

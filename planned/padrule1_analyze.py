"""PADRULE1 analysis: P R1-R6 and checks from out/padrule1_*.json (K4 against out/stands1_*.json); writes planned/padrule1_results_table.md. Usage: python3 -I planned/padrule1_analyze.py"""
import json, glob, math, statistics as st
R, k3m, k2b = [], 0, 0
for f in sorted(glob.glob('out/padrule1_[0-9].json')):
    d = json.load(open(f)); R += d['rows']; k3m += d['k3missing']; k2b += d['k2bad']
S1 = [x for f in sorted(glob.glob('out/stands1_[0-9].json')) for x in json.load(open(f))['rows']]
NS = {'DFW': 4, 'HOU': 3}; RATES = [1.5, 3, 6, 12]; SS = [3, 4, 5, 6, 8, 10, 12, 16]
IDX = {(x['metro'], x['r'], x['s'], x['rule'], x['S'], x['pads']): x for x in R}
def get(m, r, s, rule, S, pads): return IDX[(m, r, s, rule, S, pads)]
def fleet(m, r): return st.median([get(m, r, s, 'slot', None, 2)['F'] for s in range(1, 11)])
def grid(v): return next((u for u in SS if u >= v), 99)
def nmeet(m, r, rule, S, pads): return sum(bool(get(m, r, s, rule, S, pads)['meets']) for s in range(1, 11))
res = []
def add(n, ok, d): res.append((n, ok, d)); print(('PASS ' if ok else 'FAIL ') + n, d)
print(f'runs {len(R)}, K2 bad {k2b}, K3 missing {k3m}')
# K4
bad4 = 0; n4 = 0
for x in R:
    if x['rule'] == 'arrive' and x['pads'] == 2 and x['S'] in (3, 4, 5, 6, 8, 10, 12, 16) and not x.get('cannotPark') and (x['s'] % 3 == 1) and n4 < 40:
        y = next((z for z in S1 if z['metro'] == x['metro'] and z['r'] == x['r'] and z['s'] == x['s'] and z['arm'] == 'S' + str(x['S'])), None)
        if y is None or y.get('cannotPark'): continue
        n4 += 1
        if any(abs(x[k] - y[k]) > 1e-9 for k in ('servedShare', 'medWait', 'holdP95', 'belowShare')): bad4 += 1
add('K4 arrive+2 pads reproduces STANDS1', n4 >= 10 and bad4 == 0, {'compared': n4, 'differ': bad4})
add('K2 ledger <= stands in all limited runs', k2b == 0, k2b)
a = {f'{m} {r}': nmeet(m, r, 'slot', None, 2) for m, r in [('DFW', 1.5), ('DFW', 3), ('HOU', 1.5), ('HOU', 3), ('HOU', 6)]}
add('R1 slot+unlimited+2 pads meets >= 8/10 (DFW 1.5, 3; HOU 1.5, 3, 6)', all(v >= 8 for v in a.values()), a)
b = {}
for m in NS:
    for r in (1.5, 3): S = grid(math.ceil(fleet(m, r) / NS[m]) + 3); b[f'{m} {r} S{S}'] = nmeet(m, r, 'confirm', S, 2)
add('R2 confirm at S = ceil(F/n)+3 (grid), 2 pads, meets >= 8/10 at r 1.5, 3', all(v >= 8 for v in b.values()), b)
cells = []; 
for m in NS:
    for r in RATES:
        S = grid(math.ceil(fleet(m, r) / NS[m]) + 2); cs = [get(m, r, s, 'confirm', S, 2) for s in range(1, 11)]; ss = [get(m, r, s, 'slot', S, 2) for s in range(1, 11)]
        if any(x.get('cannotPark') for x in cs + ss): continue
        mc, ms = st.median([x['medWait'] for x in cs if x['medWait'] is not None] or [1e9]), st.median([x['medWait'] for x in ss if x['medWait'] is not None] or [1e9]); cells.append((m, r, S, round(mc, 1), round(ms, 1), mc > ms))
add('R3 confirm median wait > slot at S = ceil(F/n)+2 in >= 6 cells where both can park', sum(c[5] for c in cells) >= 6, {'cells_parkable': len(cells), 'confirm_higher': sum(c[5] for c in cells), 'detail': cells})
c4 = {}
for m in NS:
    S = grid(math.ceil(fleet(m, 3) / NS[m])); c4[f'{m} S{S}'] = sum(get(m, 3, s, 'confirm', S, 2).get('swaps', 0) > 0 for s in range(1, 11))
add('R4 confirm swaps in >= 3/10 seeds at S = ceil(F/n), r = 3', all(v >= 3 for v in c4.values()), c4)
c5 = {m: nmeet(m, 6, 'slot', 10, 4) for m in NS}
add('R5 slot S=10, 4 pads meets >= 8/10 at r = 6', all(v >= 8 for v in c5.values()), c5)
c6 = {}; ok6 = True
for m in NS:
    for r in (1.5, 3):
        S = grid(math.ceil(fleet(m, r) / NS[m]) + 2); xs = [get(m, r, s, 'confirm', S, 2) for s in range(1, 11)]
        for Sx in [u for u in SS if u >= S]:
            ys = [get(m, r, s, 'confirm', Sx, 2) for s in range(1, 11)]; ys = [y for y in ys if not y.get('cannotPark')]
            w = sum(y['stillWaitingToLaunch'] for y in ys); c6[f'{m} {r} S{Sx}'] = w; ok6 &= (w == 0)
add('R6 confirm leaves no aircraft waiting to take off (r <= 3, S >= ceil(F/n)+2, 2 pads)', ok6, {k: v for k, v in c6.items() if v})
n = sum(1 for x in res[2:] if x[1]); print(f'\n{n} of 6 predictions passed')
# table
L = ['# PADRULE1 results table (generated by planned/padrule1_analyze.py)\n', f'runs {len(R)}; K2 bad {k2b}; K3 missing {k3m}\n']
for m in NS:
    for pads in (2, 4):
        L += [f'\n## {m}, {pads} pads per site: seeds meeting the criterion (of 10), by uniform stands per site\n', '| r | fleet | rule | ' + ' | '.join('S' + str(u) for u in SS) + ' | unlimited | S* median |', '|---' * (len(SS) + 5) + '|']
        for r in RATES:
            for rule in ('arrive', 'slot', 'confirm'):
                per = [next((u for u in SS if get(m, r, s, rule, u, pads)['meets']), 99) for s in range(1, 11)]
                L.append(f"| {r} | {fleet(m, r):.0f} | {rule} | " + ' | '.join(('cp' if all(get(m, r, s, rule, u, pads).get('cannotPark') for s in range(1, 11)) else str(nmeet(m, r, rule, u, pads))) for u in SS) + f" | {nmeet(m, r, 'slot', None, pads) if rule == 'slot' else ''} | {'>16' if st.median(per) == 99 else st.median(per)} |")
L.append('\n## Predictions\n'); L += [f"- {'PASS' if ok else 'FAIL'} {a_}: {b_}" for a_, ok, b_ in res]
open('planned/padrule1_results_table.md', 'w').write('\n'.join(L) + '\n')

#!/usr/bin/env python3
"""ERRORS1 analysis (registration planned/ERRORS1_PREREG.md). Run from the repo root after planned/errors1_run.js.
Reads out/errors1/*.jsonl, prints the verdict on each registered prediction and writes planned/errors1_results_table.md."""
import glob, json, random, io, sys
R = [json.loads(l) for f in sorted(glob.glob('out/errors1/*.jsonl')) for l in open(f) if l.strip()]
A = [r for r in R if r['study'] == 'A']; B = [r for r in R if r['study'] == 'B']
METROS = ('houston', 'dfw'); LEVELS = ('L0', 'L1', 'L2', 'L3', 'L4')
def rows(S, **kw): return [r for r in S if all(r[k] == v for k, v in kw.items())]
def cut(m, lv, seeds=None, ci=False):
    """Study A: 1 - sum(A2 v10) / sum(A0 v10), pooled over seeds present in both arms; ci -> bootstrap over seeds (2000 resamples, seed 1)."""
    a0 = {r['seed']: r['v10'] for r in rows(A, metro=m, level=lv, arm='A0')}; a2 = {r['seed']: r['v10'] for r in rows(A, metro=m, level=lv, arm='A2')}
    ss = sorted(set(a0) & set(a2) & (set(seeds) if seeds else set(a0)))
    f = lambda s: 1 - sum(a2[x] for x in s) / sum(a0[x] for x in s) if sum(a0[x] for x in s) else float('nan')
    if not ss: return (float('nan'),) * (3 if ci else 1)
    if not ci: return f(ss)
    g = random.Random(1); bs = sorted(f([g.choice(ss) for _ in ss]) for _ in range(2000))
    return f(ss), bs[50], bs[1949]
def removal(m, lv, arm, ci=False):
    n0 = {r['seed']: r['wide'] for r in rows(B, metro=m, level=lv, arm='NONE')}; n1 = {r['seed']: r['wide'] for r in rows(B, metro=m, level=lv, arm=arm)}
    ss = sorted(set(n0) & set(n1)); f = lambda s: 1 - sum(n1[x] for x in s) / sum(n0[x] for x in s) if sum(n0[x] for x in s) else float('nan')
    if not ss: return (float('nan'),) * (3 if ci else 1)
    if not ci: return f(ss)
    g = random.Random(1); bs = sorted(f([g.choice(ss) for _ in ss]) for _ in range(2000))
    return f(ss), bs[50], bs[1949]
def flown(m, lv, arm): return sum(r['wide'] for r in rows(B, metro=m, level=lv, arm=arm))
def dshare(m, lv, arm): x = rows(B, metro=m, level=lv, arm=arm); n = sum(r['n'] for r in x); return sum(r['delayed'] for r in x) / n if n else float('nan')
P = []
def chk(name, ok, text): P.append((name, ok, text)); print('PASS' if ok else 'FAIL', name, text)
def both(fn): return {m: fn(m) for m in METROS}
def fmt(d, p=True): return ', '.join(f'{m} {100 * v:.0f} %' if p else f'{m} {v:.2f}' for m, v in d.items())
c = {lv: both(lambda m, lv=lv: cut(m, lv)) for lv in LEVELS}
chk('E1', all(c['L1'][m] >= 0.60 for m in METROS), 'cut at L1: ' + fmt(c['L1']))
chk('E2', all(0.30 <= c['L2'][m] <= 0.60 for m in METROS), 'cut at L2: ' + fmt(c['L2']))
chk('E3', all(c['L3'][m] < 0.25 for m in METROS), 'cut at L3: ' + fmt(c['L3']))
chk('E4', all(c['L4'][m] < 0.15 for m in METROS), 'cut at L4: ' + fmt(c['L4']))
chk('E5', all(c[LEVELS[i + 1]][m] <= c[LEVELS[i]][m] + 0.03 for i in range(4) for m in METROS), 'cut by level: ' + '; '.join(f'{m} ' + ' > '.join(f'{100 * c[lv][m]:.0f}' for lv in LEVELS) for m in METROS))
S4 = (1, 2, 3, 4); base = both(lambda m: cut(m, 'L0', S4))
d = {x: both(lambda m, x=x: base[m] - cut(m, x, S4)) for x in ('Z4', 'H4', 'T4')}
chk('E6a', all(d['Z4'][m] >= 0.40 for m in METROS), 'cut lost to height error alone (points of cut, seeds 1-4): ' + fmt(d['Z4']))
chk('E6b', all(abs(d['H4'][m]) <= 0.10 for m in METROS), 'change with sideways error alone: ' + fmt(d['H4']))
chk('E6c', all(abs(d['T4'][m]) <= 0.10 for m in METROS), 'change with late start alone: ' + fmt(d['T4']))
rm = {(lv, a): both(lambda m, lv=lv, a=a: removal(m, lv, a)) for lv in ('L0', 'L2', 'L4') for a in ('V2', 'V3')}
chk('E7', all(rm[('L0', 'V2')][m] >= 0.98 for m in METROS), 'V2 removal at L0: ' + fmt(rm[('L0', 'V2')]))
chk('E8', all(0.75 <= rm[('L2', 'V2')][m] <= 0.97 for m in METROS), 'V2 removal at L2: ' + fmt(rm[('L2', 'V2')]))
chk('E9', all(rm[('L4', 'V2')][m] < 0.90 for m in METROS), 'V2 removal at L4: ' + fmt(rm[('L4', 'V2')]))
chk('E10', all(flown(m, lv, 'V3') < flown(m, lv, 'V2') for m in METROS for lv in ('L2', 'L4')), 'flown conflicts V3 vs V2: ' + '; '.join(f'{m} {lv} {flown(m, lv, "V3")} vs {flown(m, lv, "V2")}' for m in METROS for lv in ('L2', 'L4')))
r11 = both(lambda m: dshare(m, 'L0', 'V3') / dshare(m, 'L0', 'V2'))
chk('E11', all(r11[m] >= 1.5 for m in METROS), 'delayed share V3 / V2 at L0: ' + fmt(r11, False) + '; V2 ' + fmt(both(lambda m: dshare(m, 'L0', 'V2'))) + ', V3 ' + fmt(both(lambda m: dshare(m, 'L0', 'V3'))))
npass = sum(1 for _, ok, _ in P if ok)
L = ['# ERRORS1 results table (generated by planned/errors1_analyze.py)', '', f'{npass} of {len(P)} predictions passed. Runs: Study A {len(A)}, Study B {len(B)}.', '']
L += [f'- {"PASS" if ok else "FAIL"} {n}: {t}' for n, ok, t in P]
L += ['', '## Study A: conflicts cut by height sharing, by error level (pooled over seeds; 95 % bootstrap interval over seeds)', '', '| Metro | Level | Seeds | A0 conflicts | A2 conflicts | Cut [95 %] |', '|---|---|---|---|---|---|']
for m in METROS:
    for lv in LEVELS + ('H4', 'Z4', 'T4'):
        a0 = rows(A, metro=m, level=lv, arm='A0'); a2 = rows(A, metro=m, level=lv, arm='A2')
        if not a0: continue
        f, lo, hi = cut(m, lv, ci=True); L.append(f'| {m} | {lv} | {len(a0)} | {sum(r["v10"] for r in a0)} | {sum(r["v10"] for r in a2)} | {100 * f:.0f} % [{100 * lo:.0f}-{100 * hi:.0f}] |')
L += ['', '## Study A: close calls (15 m, 5 m), A0 vs A2 conflicts at wider gaps (v15, v20)', '', '| Metro | Level | A0 close | A2 close | A0 v15 | A2 v15 | A0 v20 | A2 v20 |', '|---|---|---|---|---|---|---|---|']
for m in METROS:
    for lv in LEVELS:
        a0 = rows(A, metro=m, level=lv, arm='A0'); a2 = rows(A, metro=m, level=lv, arm='A2')
        if a0: L.append(f'| {m} | {lv} | ' + ' | '.join(str(sum(r[k] for r in x)) for k in ('close', 'v15', 'v20') for x in (a0, a2)) + ' |')
L += ['', '## Study B: flown conflicts under the plan check, by error level', '', '| Metro | Level | Seeds | Flown conflicts none / V2 / V3 | Removed by V2 [95 %] | Removed by V3 [95 %] | Delayed share V2 / V3 | Mean delay V2 (min) |', '|---|---|---|---|---|---|---|---|']
for m in METROS:
    for lv in ('L0', 'L2', 'L4'):
        x = rows(B, metro=m, level=lv, arm='V2')
        if not x: continue
        r2 = removal(m, lv, 'V2', True); r3 = removal(m, lv, 'V3', True); dsum = sum(r['delayed'] for r in x)
        md = sum(r['meanD'] * r['delayed'] for r in x) / dsum / 60 if dsum else 0
        L.append(f'| {m} | {lv} | {len(x)} | {flown(m, lv, "NONE")} / {flown(m, lv, "V2")} / {flown(m, lv, "V3")} | {100 * r2[0]:.1f} % [{100 * r2[1]:.1f}-{100 * r2[2]:.1f}] | {100 * r3[0]:.1f} % [{100 * r3[1]:.1f}-{100 * r3[2]:.1f}] | {100 * dshare(m, lv, "V2"):.1f} % / {100 * dshare(m, lv, "V3"):.1f} % | {md:.1f} |')
open('planned/errors1_results_table.md', 'w').write('\n'.join(L) + '\n'); print(f'{npass} of {len(P)} passed')

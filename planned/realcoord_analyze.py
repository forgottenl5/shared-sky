#!/usr/bin/env python3
"""REALCOORD analysis (planned/REALCOORD_PREREG.md). Pooled over seeds 1-10, as SEEDS2; paired percentile bootstrap over seeds for intervals."""
import json, glob, random
R = [json.loads(l) for f in glob.glob('out/realcoord/*.jsonl') for l in open(f) if l.strip()]
def sel(m, h, a, seeds=None): return [r for r in R if r['metro'] == m and r['heights'] == h and r['arm'] == a and (seeds is None or r['seed'] in seeds)]
def dshare(m, h, seeds=None):
    x = sel(m, h, 'V2', seeds); n = sum(r['cost']['all']['n'] for r in x); return sum(r['cost']['all']['delayed'] for r in x) / n if n else float('nan')
def meanD(m, h): x = sel(m, h, 'V2'); d = sum(r['cost']['all']['delayed'] for r in x); return sum(r['cost']['all']['meanD'] * r['cost']['all']['delayed'] for r in x) / d / 60
def wide(m, h, a, seeds=None): return sum(r['wide'] for r in sel(m, h, a, seeds))
def boot(f, B=10000):
    seeds = sorted({r['seed'] for r in R}); rng = random.Random(1); v = []
    for _ in range(B):
        s = [rng.choice(seeds) for _ in seeds]; v.append(f(s))
    v.sort(); return v[int(0.025 * B)], v[int(0.975 * B) - 1]
def ds_list(m, h, s):  # resampled seeds may repeat: pool with multiplicity
    x = [r for k in s for r in sel(m, h, 'V2', {k})]; n = sum(r['cost']['all']['n'] for r in x); return sum(r['cost']['all']['delayed'] for r in x) / n
P = []
def chk(n, ok, t): P.append((n, ok, t)); print('PASS' if ok else 'FAIL', n, t)
M = ('houston', 'dfw')
d2 = {m: dshare(m, 'A2') for m in M}; d0 = {m: dshare(m, 'A0') for m in M}
chk('W1', 0.12 <= d2['houston'] <= 0.26 and 0.11 <= d2['dfw'] <= 0.24, ', '.join(f'{m} {100 * d2[m]:.1f} %' for m in M))
ratio = {m: d0[m] / d2[m] for m in M}
chk('W2', all(1.5 <= v <= 2.6 for v in ratio.values()), ', '.join(f'{m} {v:.2f}' for m, v in ratio.items()))
cuts = {(m, h): 1 - wide(m, h, 'V2') / wide(m, h, 'NONE') for m in M for h in ('A0', 'A2')}
chk('W3', all(v >= 0.95 for v in cuts.values()), ', '.join(f'{m} {h} {100 * v:.1f} %' for (m, h), v in cuts.items()))
nc = {m: 1 - wide(m, 'A2', 'NONE') / wide(m, 'A0', 'NONE') for m in M}
chk('W4', all(v >= 0.65 for v in nc.values()), ', '.join(f'{m} {100 * v:.1f} % ({wide(m, "A0", "NONE")} -> {wide(m, "A2", "NONE")})' for m, v in nc.items()))
npass = sum(1 for _, ok, _ in P if ok)
L = ['# REALCOORD results table (generated by planned/realcoord_analyze.py)', '', f'{npass} of {len(P)} predictions passed. Runs: {len(R)}.', ''] + [f'- {"PASS" if ok else "FAIL"} {n}: {t}' for n, ok, t in P]
L += ['', '| Metro | Heights | Runs (V2) | Delayed share (95 % interval) | Mean delay of delayed (min) | Flown conflicts, none / V2 | Cut by V2 |', '|---|---|---|---|---|---|---|']
for m in M:
    for h in ('A0', 'A2'):
        lo, hi = boot(lambda s: ds_list(m, h, s), 2000)
        L.append(f'| {m} | {h} | {len(sel(m, h, "V2"))} | {100 * dshare(m, h):.1f} % ({100 * lo:.1f}-{100 * hi:.1f}) | {meanD(m, h):.1f} | {wide(m, h, "NONE")} / {wide(m, h, "V2")} | {100 * cuts[(m, h)]:.1f} % |')
L += ['', '| Metro | A0 / A2 delayed-share ratio (95 % interval, paired by seed) |', '|---|---|']
for m in M:
    lo, hi = boot(lambda s: ds_list(m, 'A0', s) / ds_list(m, 'A2', s), 2000); L.append(f'| {m} | {ratio[m]:.2f} ({lo:.2f}-{hi:.2f}) |')
L += ['', '| Metro | Heights | Delayed share by company (V2) |', '|---|---|---|']
for m in M:
    for h in ('A0', 'A2'):
        x = sel(m, h, 'V2'); ops = sorted({k for r in x for k in r['cost'] if k != 'all'})
        L.append(f'| {m} | {h} | ' + ', '.join(f'{o} {100 * sum(r["cost"][o]["delayed"] for r in x if o in r["cost"]) / max(1, sum(r["cost"][o]["n"] for r in x if o in r["cost"])):.1f} %' for o in ops) + ' |')
open('planned/realcoord_results_table.md', 'w').write('\n'.join(L) + '\n'); print(f'{npass} of {len(P)} passed')

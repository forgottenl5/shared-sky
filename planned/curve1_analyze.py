#!/usr/bin/env python3
"""CURVE1 analysis (planned/CURVE1_PREREG.md)."""
import json, glob, random
R = [json.loads(l) for f in glob.glob('out/curve1/*.jsonl') for l in open(f) if l.strip()]
H2 = {(r['metro'], r['arm'], r['seed']): r for f in glob.glob('out/headline2/*.jsonl') for l in open(f) if l.strip() for r in [json.loads(l)]}
HZ, VT, M = [20, 30, 40, 50], [5, 7.5, 10, 12.5, 15, 20], ('houston', 'dfw')
key = lambda h, v: f'h{h}v{v:g}'
def tot(m, a, k, seeds=None): return sum(r['counts'][k] for r in R if r['metro'] == m and r['arm'] == a and (seeds is None or r['seed'] in seeds))
def cutk(m, k, seeds=None): s = tot(m, 'S1', k, seeds); return 1 - tot(m, 'A2', k, seeds) / s if s else float('nan')
def boot(m, k, B=2000):
    seeds = sorted({r['seed'] for r in R}); rng = random.Random(7); v = []
    for _ in range(B):
        s = [rng.choice(seeds) for _ in seeds]; S = sum(tot(m, 'S1', k, {x}) for x in s); A = sum(tot(m, 'A2', k, {x}) for x in s); v.append(1 - A / S if S else float('nan'))
    v.sort(); return v[int(0.025 * B)], v[int(0.975 * B) - 1]
# checks
k1 = all(H2[(r['metro'], r['arm'], r['seed'])]['v10'] == r['counts']['h30v10'] and H2[(r['metro'], r['arm'], r['seed'])]['v15'] == r['counts']['h30v15'] and H2[(r['metro'], r['arm'], r['seed'])]['v20'] == r['counts']['h30v20'] for r in R)
k2 = all(r['counts'][key(HZ[i], VT[j])] <= r['counts'][key(HZ[i2], VT[j2])] for r in R for i in range(4) for j in range(6) for i2 in range(i, 4) for j2 in range(j, 6))
print('K1', 'PASS' if k1 else 'FAIL', '| K2', 'PASS' if k2 else 'FAIL', '| runs', len(R))
C = {(m, h, v): cutk(m, key(h, v)) for m in M for h in HZ for v in VT}
P = []
def chk(n, ok, t): P.append((n, ok, t)); print('PASS' if ok else 'FAIL', n, t)
chk('T1', all(C[(m, h, 5)] >= 0.80 for m in M for h in HZ), ', '.join(f'{m} {min(C[(m, h, 5)] for h in HZ) * 100:.0f}-{max(C[(m, h, 5)] for h in HZ) * 100:.0f} %' for m in M))
chk('T2', all(C[(m, h, 15)] < C[(m, h, 10)] and C[(m, h, 15)] < C[(m, h, 20)] for m in M for h in HZ), '; '.join(f'{m} h{h}: {C[(m, h, 10)] * 100:.0f} / {C[(m, h, 15)] * 100:.0f} / {C[(m, h, 20)] * 100:.0f} %' for m in M for h in HZ))
chk('T3', all(max(C[(m, h, 10)] for h in HZ) - min(C[(m, h, 10)] for h in HZ) <= 0.10 for m in M), ', '.join(f'{m} {min(C[(m, h, 10)] for h in HZ) * 100:.0f}-{max(C[(m, h, 10)] for h in HZ) * 100:.0f} %' for m in M))
chk('T4', all(min(C[(m, h, v)] for h in HZ for v in VT) >= 0.35 for m in M), ', '.join(f'{m} min {min(C[(m, h, v)] for h in HZ for v in VT) * 100:.0f} %' for m in M))
npass = sum(1 for _, ok, _ in P if ok)
L = ['# CURVE1 results table (generated by planned/curve1_analyze.py)', '', f'{npass} of {len(P)} predictions passed. K1 {"PASS" if k1 else "FAIL"}, K2 {"PASS" if k2 else "FAIL"}. Runs: {len(R)}.', ''] + [f'- {"PASS" if ok else "FAIL"} {n}: {t}' for n, ok, t in P]
for m in M:
    L += ['', f'## {m}: cut, shared out (A2) vs best-sourced Amazon (S1), 95 % interval', '', '| horizontal \\ vertical | ' + ' | '.join(f'{v:g} m' for v in VT) + ' |', '|---|' + '---|' * len(VT)]
    for h in HZ:
        cells = []
        for v in VT: lo, hi = boot(m, key(h, v)); cells.append(f'{C[(m, h, v)] * 100:.0f} % ({lo * 100:.0f}-{hi * 100:.0f})')
        L.append(f'| {h} m | ' + ' | '.join(cells) + ' |')
    L += ['', f'Conflicts per hour (pooled, S1 / A2), 30 m horizontal: ' + ', '.join(f'{v:g} m {tot(m, "S1", key(30, v)) / 20:.1f} / {tot(m, "A2", key(30, v)) / 20:.1f}' for v in VT)]
    pr = {}
    for r in R:
        if r['metro'] == m and r['arm'] == 'A2':
            for p, c in r['pairs'].get('h30v15', {}).items(): pr[p] = pr.get(p, 0) + c
    pr10 = {}
    for r in R:
        if r['metro'] == m and r['arm'] == 'A2':
            for p, c in r['pairs'].get('h30v10', {}).items(): pr10[p] = pr10.get(p, 0) + c
    L.append(f'A2 company pairs at 30 m: 10 m {pr10}; 15 m {pr}')
open('planned/curve1_results_table.md', 'w').write('\n'.join(L) + '\n'); print(f'{npass} of {len(P)} passed')

#!/usr/bin/env python3
"""CAPS1 analysis (registration planned/CAPS1_PREREG.md): capped runs out/caps1 vs HEADLINE2 out/headline2."""
import json, glob
C = [json.loads(l) for f in glob.glob('out/caps1/*.jsonl') for l in open(f) if l.strip()]
S = [json.loads(l) for f in glob.glob('out/headline2/*.jsonl') for l in open(f) if l.strip()]
def rows(R, m, arm): return [r for r in R if r['metro'] == m and r['arm'] == arm]
def ph(R, m, arm): v = [r['v10'] for r in rows(R, m, arm)]; return sum(v) / len(v) / 2
P = []
def chk(n, ok, t): P.append((n, ok, t)); print('PASS' if ok else 'FAIL', n, t)
res = {m: dict(s1c=ph(C, m, 'S1'), a2c=ph(C, m, 'A2'), s1s=ph(S, m, 'S1'), a2s=ph(S, m, 'A2')) for m in ('houston', 'dfw')}
for r in res.values(): r['cutc'] = 1 - r['a2c'] / r['s1c']; r['cuts'] = 1 - r['a2s'] / r['s1s']
q1 = {m: {op: sum(r['byOp'].get(op, 0) for r in rows(C, m, 'S1')) / sum(r['byOpUncapped'][op] for r in rows(C, m, 'S1')) for op in ('wing', 'zipline')} for m in ('houston', 'dfw')}
chk('Q1', all(0.15 <= q1[m]['wing'] <= 0.40 and 0.06 <= q1[m]['zipline'] <= 0.25 for m in q1), ', '.join(f"{m} Wing {100 * q1[m]['wing']:.0f} %, Zipline {100 * q1[m]['zipline']:.0f} %" for m in q1))
chk('Q2', all(0.60 <= 1 - r['s1c'] / r['s1s'] <= 0.95 for r in res.values()), ', '.join(f"{m} S1 {r['s1c']:.1f} vs {r['s1s']:.1f}/h ({100 * (1 - r['s1c'] / r['s1s']):.0f} % fewer)" for m, r in res.items()))
chk('Q3', all(0.50 <= r['cutc'] <= 0.90 for r in res.values()), ', '.join(f"{m} cut {100 * r['cutc']:.0f} % (uncapped {100 * r['cuts']:.0f} %)" for m, r in res.items()))
q4 = {}
for m in ('houston', 'dfw'):
    tot = {}
    for r in rows(C, m, 'S1'):
        for k, v in r['pairs'].items(): tot[k] = tot.get(k, 0) + v
    q4[m] = sum(v for k, v in tot.items() if 'amazon' in k) / max(1, sum(tot.values()))
chk('Q4', all(v >= 0.60 for v in q4.values()), ', '.join(f'{m} Amazon pairs {100 * v:.0f} %' for m, v in q4.items()))
npass = sum(1 for _, ok, _ in P if ok)
L = ['# CAPS1 results table (generated by planned/caps1_analyze.py)', '', f'{npass} of {len(P)} predictions passed.', ''] + [f'- {"PASS" if ok else "FAIL"} {n}: {t}' for n, ok, t in P]
L += ['', '| Metro | S1 uncapped /h | S1 capped /h | A2 uncapped /h | A2 capped /h | Cut uncapped | Cut capped |', '|---|---|---|---|---|---|---|']
L += [f"| {m} | {r['s1s']:.1f} | {r['s1c']:.1f} | {r['a2s']:.1f} | {r['a2c']:.1f} | {100 * r['cuts']:.0f} % | {100 * r['cutc']:.0f} % |" for m, r in res.items()]
open('planned/caps1_results_table.md', 'w').write('\n'.join(L) + '\n'); print(f'{npass} of {len(P)} passed')

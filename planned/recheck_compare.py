#!/usr/bin/env python3
"""RECHECK_A1 analysis (planned/RECHECK_A1_PREREG.md). Written and committed before the re-check runs.

Runs each study's own, unchanged analysis script twice: in the repo root (original runs, out/) and in the re-check shadow root
(fixes on). Pairs their verdict lines in order and scores the registered predictions P1-P3.
Usage: python3 planned/recheck_compare.py <shadow root>   (from the repo root) -> markdown on stdout
"""
import glob, json, os, re, subprocess, sys
from collections import defaultdict

REPO = os.getcwd(); NEW = os.path.abspath(sys.argv[1])
STUDIES = [("PRELAUNCH", "prelaunch", "out/prelaunch/runs_*.jsonl"), ("PRELAUNCH2", "prelaunch2", "out/prelaunch2/runs_*.jsonl"),
           ("AMZBAND", "amzband", "out/amzband/runs.jsonl"), ("DFWBAD", "dfwbad", "out/dfwbad/runs_*.jsonl"),
           ("DFWPROC", "dfwproc", "out/dfwproc/runs_*.jsonl"), ("RTHREP", "rthrep", "out/rthrep/runs_*.jsonl")]
GROUP = ["study", "part", "kind", "arm", "d", "zsig", "boxes"]
VERD = re.compile(r"\*\*(PASS|FAIL)\*\*")

def verdicts(root, script):
    out = subprocess.run([sys.executable, f"planned/{script}_analyze.py"], cwd=root, capture_output=True, text=True).stdout
    return [(l.strip(), VERD.findall(l)) for l in out.splitlines() if VERD.search(l)]

def rows(root, pat):
    return [json.loads(l) for f in sorted(glob.glob(os.path.join(root, pat))) for l in open(f) if l.strip()]

def cells(R):
    c = defaultdict(lambda: [0, 0, 0])
    for r in R:
        k = tuple((g, json.dumps(r[g])) for g in GROUP if g in r)
        c[k][0] += r["cross_wide"]; c[k][1] += r["cross_close"]; c[k][2] += 1
    return c

def name(k): return " ".join(f"{g}={json.loads(v)}" for g, v in k if json.loads(v) not in (None, 0) or g == "d")

P = print
P("# RECHECK_A1 results table (generated by planned/recheck_compare.py)\n")
flips, total = [], 0
p1 = []; p2 = []
for S, script, pat in STUDIES:
    old, new = verdicts(REPO, script), verdicts(NEW, script)
    P(f"## {S}\n")
    P(f"Runs: {len(rows(REPO, pat))} original, {len(rows(NEW, pat))} re-check.\n")
    P("| # | verdict line (re-check run) | original | re-check |"); P("|---|---|---|---|")
    if len(old) != len(new): P(f"| — | VERDICT LINE COUNT DIFFERS: {len(old)} original vs {len(new)} re-check | | |")
    for i, ((lo, vo), (ln, vn)) in enumerate(zip(old, new), 1):
        total += 1; ch = vo != vn
        if ch: flips.append((S, i, ln))
        P(f"| {i} | {ln[:160].replace('|', '/')} | {'/'.join(vo)} | {'/'.join(vn)}{' **CHANGED**' if ch else ''} |")
    co, cn = cells(rows(REPO, pat)), cells(rows(NEW, pat))
    P("\n| cell | wide original → re-check | change | close original → re-check |"); P("|---|---|---|---|")
    for k in sorted(co, key=str):
        a, b = co[k], cn.get(k, [0, 0, 0]); chg = None if a[0] == 0 else (b[0] - a[0]) / a[0]
        dev = any(g == "kind" and json.loads(v) not in ("none",) for g, v in k)
        z = any(g == "zsig" and json.loads(v) for g, v in k)
        if dev:
            if a[0] >= 10: p2.append((S, name(k), a[0], b[0]))
        elif not z and a[0] >= 20: p1.append((S, name(k), a[0], b[0], chg))
        P(f"| {name(k)} | {a[0]} → {b[0]} | {'—' if chg is None else f'{100 * chg:+.1f} %'} | {a[1]} → {b[1]} |")
    P("")

P("## Registered predictions\n")
ok1 = all(abs(c) <= 0.06 for *_, c in p1)
P(f"- **P1** (cells without an off-plan event or height error, original wide >= 20: every pooled wide count within ±6 %): "
  f"{len(p1)} cells, largest change {max((abs(c) for *_, c in p1), default=0) * 100:.1f} %. {'**PASS**' if ok1 else '**FAIL**'}")
up = sum(1 for *_, a, b in p2 if b >= a)
ok2 = len(p2) > 0 and up * 3 >= 2 * len(p2)
P(f"- **P2** (off-plan cells with original wide >= 10: re-check count >= original in at least two thirds): {up} of {len(p2)}. {'**PASS**' if ok2 else '**FAIL**'}")
P(f"- **P3** (at most 3 of the {total} original verdicts change): {len(flips)} changed. {'**PASS**' if len(flips) <= 3 else '**FAIL**'}")
for S, i, l in flips: P(f"  - {S} #{i}: {l[:200]}")

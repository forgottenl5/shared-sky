#!/usr/bin/env python3
"""SEEDS2 analysis (registration planned/SEEDS2_PREREG.md): COORD1 seeds 1-3 pooled with SEEDS2 seeds 4-10, arms NONE and V2."""
import json, glob
R = [json.loads(l) for d in ('out/coord1', 'out/seeds2') for f in glob.glob(d + '/*.jsonl') for l in open(f) if l.strip()]
R = [r for r in R if r['arm'] in ('NONE', 'V2')]
def sel(m, h, a): return [r for r in R if r['metro'] == m and r['heights'] == h and r['arm'] == a]
def delayed(m, h): x = sel(m, h, 'V2'); n = sum(r['cost']['all']['n'] for r in x); d = sum(r['cost']['all']['delayed'] for r in x); return d / n, len(x)
def meanD(m, h): x = sel(m, h, 'V2'); d = sum(r['cost']['all']['delayed'] for r in x); return sum(r['cost']['all']['meanD'] * r['cost']['all']['delayed'] for r in x) / d / 60
def cut(m, h): a = sum(r['wide'] for r in sel(m, h, 'NONE')); b = sum(r['wide'] for r in sel(m, h, 'V2')); return 1 - b / a
P = []
def chk(n, ok, t): P.append((n, ok, t)); print('PASS' if ok else 'FAIL', n, t)
dh, nh = delayed('houston', 'A2'); dd, nd = delayed('dfw', 'A2')
chk('S1', 0.15 <= dh <= 0.24 and 0.13 <= dd <= 0.21, f'A2+V2 delayed: Houston {100 * dh:.1f} % ({nh} runs), DFW {100 * dd:.1f} % ({nd} runs)')
cuts = {(m, h): cut(m, h) for m in ('houston', 'dfw') for h in ('A0', 'A2')}
chk('S2', all(v >= 0.93 for v in cuts.values()), ', '.join(f'{m} {h} {100 * v:.1f} %' for (m, h), v in cuts.items()))
ratio = {m: delayed(m, 'A0')[0] / delayed(m, 'A2')[0] for m in ('houston', 'dfw')}
chk('S3', all(1.6 <= v <= 2.5 for v in ratio.values()), ', '.join(f'{m} {v:.2f}' for m, v in ratio.items()))
md = {m: meanD(m, 'A2') for m in ('houston', 'dfw')}
chk('S4', all(4 <= v <= 8 for v in md.values()), ', '.join(f'{m} {v:.1f} min' for m, v in md.items()))
npass = sum(1 for _, ok, _ in P if ok)
L = ['# SEEDS2 results table (generated by planned/seeds2_analyze.py)', '', f'{npass} of {len(P)} predictions passed.', ''] + [f'- {"PASS" if ok else "FAIL"} {n}: {t}' for n, ok, t in P]
L += ['', '| Metro | Heights | Runs | Delayed (V2) | Mean delay of delayed (min) | Flown conflicts cut, V2 vs none |', '|---|---|---|---|---|---|']
for m in ('houston', 'dfw'):
    for h in ('A0', 'A2'): d, n = delayed(m, h); L.append(f'| {m} | {h} | {n} | {100 * d:.1f} % | {meanD(m, h):.1f} | {100 * cuts[(m, h)]:.1f} % |')
open('planned/seeds2_results_table.md', 'w').write('\n'.join(L) + '\n'); print(f'{npass} of {len(P)} passed')

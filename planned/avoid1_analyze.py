#!/usr/bin/env python3
"""AVOID1 analysis (registration planned/AVOID1_PREREG.md). Analysis-only study on the RISK1 encounter lists (out/risk1/*.jsonl).
Each planned cross-company encounter that would trigger an alert gets a vertical avoidance manoeuvre if there is time; residual
collision risk uses the RISK1 Reich-type formula. Prints the verdict on each prediction and writes planned/avoid1_results_table.md."""
import glob, json, math, random
R = [json.loads(l) for f in sorted(glob.glob('out/risk1/*.jsonl')) for l in open(f) if l.strip()]
METROS = ('houston', 'dfw'); ARMS = ('S1', 'A2'); K_RAD = math.sqrt(-2 * math.log(0.05)); K_VER = 1.96
LV = {'L0': (0, 0), 'L1': (3, 4), 'L2': (8, 13)}
WING = (0.65, 0.25); BIG = (1.5, 0.3)                 # RISK1 base sizes (half-span / half-length, half-height, m)
ALERT_H, ALERT_V = 30.0, 10.0                          # alert if the planned CPA is within 30 m sideways and 10 m vertically (the conflict threshold)
TARGET = 10.0                                          # vertical gap the manoeuvre tries to reach (m)
BASE = dict(D=300.0, tau=6.0, c=2.0, s=36 / 51)       # detection range (m), latency incl. 5 s message gaps (s), climb/descent rate (m/s), success share (BAA004 field: 36 of 51)
Phi = lambda x: 0.5 * (1 + math.erf(x / math.sqrt(2)))
def band(d, W, s): return Phi((W - d) / s) - Phi((-W - d) / s) if s > 0 else (1.0 if abs(d) < W else 0.0)
def size(op): return WING if op == 'wing' else BIG
def sig(lv): h95, v95 = LV[lv]; return math.sqrt(2) * h95 / K_RAD, math.sqrt(2) * v95 / K_VER
def avoided_dz(dz, dh, vrel, D, tau, c):
    """vertical gap at the CPA after one aircraft climbs or descends away (planned geometry); None if no alert"""
    if not (dh < ALERT_H and abs(dz) < ALERT_V): return None
    t = max(0.0, D / max(vrel, 0.1) - tau)              # time left to manoeuvre after detection and latency
    g = min(TARGET, abs(dz) + c * t); return math.copysign(g, dz if dz != 0 else 1.0)
def row_risk(row, lv, cfg):
    """(expected collisions without avoidance, with avoidance, number of alerts)"""
    sh, sz = sig(lv); p0 = p1 = 0.0; n = 0
    for opA, opB, dperp, dz, dh, vrel in row['enc']:
        A, B = size(opA), size(opB); W, Hz = A[0] + B[0], A[1] + B[1]; b = band(dperp, W, sh); q0 = b * band(dz, Hz, sz); p0 += q0
        if cfg is None: p1 += q0; continue
        g = avoided_dz(dz, dh, vrel, cfg['D'], cfg['tau'], cfg['c'])
        if g is None: p1 += q0; continue
        n += 1; p1 += cfg['s'] * b * band(g, Hz, sz) + (1 - cfg['s']) * q0
    return p0, p1, n
def rows(m, a): return {r['seed']: r for r in R if r['metro'] == m and r['arm'] == a}
def agg(m, a, lv, cfg, seeds=None):
    x = rows(m, a); ss = sorted(seeds if seeds else x); t = [row_risk(x[s], lv, cfg) for s in ss]; h = sum(x[s]['flightHours'] for s in ss)
    return 1e5 * sum(v[0] for v in t) / h, 1e5 * sum(v[1] for v in t) / h, sum(v[2] for v in t) / h
def avcut(m, a, lv, cfg): r0, r1, _ = agg(m, a, lv, cfg); return 1 - r1 / r0 if r0 else float('nan')
def armcut(m, lv, cfg): return 1 - agg(m, 'A2', lv, cfg)[1] / agg(m, 'S1', lv, cfg)[1]
P = []
def chk(name, ok, text): P.append((name, ok, text)); print('PASS' if ok else 'FAIL', name, text)
v1 = {(m, a): avcut(m, a, 'L2', BASE) for m in METROS for a in ARMS}
chk('V1', all(0.50 <= v <= 36 / 51 for v in v1.values()), 'avoidance cut in risk at L2, base settings: ' + '; '.join(f'{m} {a} {100 * v:.0f} %' for (m, a), v in v1.items()))
ideal = dict(BASE, s=1.0); v2 = {(m, a): avcut(m, a, 'L2', ideal) for m in METROS for a in ARMS}
chk('V2', all(v >= 0.90 for v in v2.values()), 'with every alert acted on (success 100 %): ' + '; '.join(f'{m} {a} {100 * v:.0f} %' for (m, a), v in v2.items()))
v3 = {m: armcut(m, 'L2', BASE) for m in METROS}
chk('V3', all(0.45 <= v <= 0.75 for v in v3.values()), 'height-sharing cut in residual risk with base avoidance at L2: ' + ', '.join(f'{m} {100 * v:.0f} %' for m, v in v3.items()))
v4 = {m: 1 - agg(m, 'A2', 'L2', BASE)[2] / agg(m, 'S1', 'L2', BASE)[2] for m in METROS}
chk('V4', all(v >= 0.50 for v in v4.values()), 'fewer avoidance manoeuvres per flight hour with shared-out heights: ' + ', '.join(f'{m} {100 * v:.0f} %' for m, v in v4.items()))
short = dict(BASE, D=100.0); v5 = {(m, a): avcut(m, a, 'L2', short) for m in METROS for a in ARMS}
chk('V5', all(v < 0.30 for v in v5.values()), 'avoidance cut with 100 m detection range: ' + '; '.join(f'{m} {a} {100 * v:.0f} %' for (m, a), v in v5.items()))
npass = sum(1 for _, ok, _ in P if ok)
T = ['# AVOID1 results table (generated by planned/avoid1_analyze.py)', '', f'{npass} of {len(P)} predictions passed. Encounter lists: RISK1, {len(R)} rows.', '']
T += [f'- {"PASS" if ok else "FAIL"} {n}: {t}' for n, ok, t in P]
T += ['', '## Collision risk per 100,000 flight hours without and with avoidance (base: 300 m detection, 6 s latency, 2 m/s, 71 % success)', '', '| Metro | Level | Arm | No avoidance | With avoidance | Cut by avoidance | Manoeuvres per flight hour |', '|---|---|---|---|---|---|---|']
for m in METROS:
    for lv in ('L0', 'L1', 'L2'):
        for a in ARMS: r0, r1, n = agg(m, a, lv, BASE); T.append(f'| {m} | {lv} | {a} | {r0:.3g} | {r1:.3g} | {100 * (1 - r1 / r0) if r0 else float("nan"):.0f} % | {n:.3f} |')
T += ['', '## Sensitivity at L2 (cut in risk by avoidance; one setting changed at a time from the base)', '', '| Metro | Arm | base | D 100 m | D 500 m | latency 2 s | 1 m/s | 4 m/s | success 100 % |', '|---|---|---|---|---|---|---|---|---|']
var = [BASE, dict(BASE, D=100.0), dict(BASE, D=500.0), dict(BASE, tau=2.0), dict(BASE, c=1.0), dict(BASE, c=4.0), ideal]
for m in METROS:
    for a in ARMS: T.append(f'| {m} | {a} | ' + ' | '.join(f'{100 * avcut(m, a, "L2", v):.0f} %' for v in var) + ' |')
T += ['', '## Height-sharing cut in residual risk, with base avoidance', '', '| Metro | L0 | L1 | L2 |', '|---|---|---|---|']
for m in METROS: T.append(f'| {m} | ' + ' | '.join(f'{100 * armcut(m, lv, BASE):.0f} %' for lv in ('L0', 'L1', 'L2')) + ' |')
open('planned/avoid1_results_table.md', 'w').write('\n'.join(T) + '\n'); print(f'{npass} of {len(P)} passed')
